#!/usr/bin/env python3
"""Тестовое наполнение вольта — чтобы было на что смотреть.

Пустая система показывает пустую ленту, и по ней не видно ни просрочки, ни
буксующих шагов, ни того, как выглядит закрытая задача рядом с отменённой.
Скрипт заводит десяток задач, которые вместе покрывают все состояния из ТЗ.

Задачи заводятся движком, а не записью YAML руками: демо-вольт обязан быть
таким же, каким его сделал бы человек через форму. Файл, собранный в обход
`cmd_create`, мог бы содержать состояние, до которого продукт не доходит,
и мы бы отлаживали то, чего в жизни не бывает.

История тоже настоящая. Каждая задача заводится «в прошлом» — команде движка
передаётся та дата, в которую это будто бы случилось, — а потом по ней
проходят обычные `done`/`notdone`/`defer`, тоже каждая своим числом. Поэтому
у буксующих шагов в журнале три переноса с разными датами, а не счётчик,
проставленный из головы.

    python3 demo.py          # завести
    python3 demo.py --clean  # убрать только своё

Своё — это задачи с тегом «демо». Чужие файлы скрипт не трогает ни при
наполнении, ни при очистке: вольт разработчика обычно не пустой.
"""
import argparse
import json
import sys
from datetime import date, timedelta
from types import SimpleNamespace

import engine

МЕТКА = "демо"
СЕГОДНЯ = date.today()


def день(сдвиг):
    return СЕГОДНЯ + timedelta(days=сдвиг)


def _args(**поля):
    поля.setdefault("reason", None)
    поля.setdefault("to", None)
    поля.setdefault("force", False)
    return SimpleNamespace(**поля)


def завести(название, теги, шаги, тело="", заведена=0):
    """Одна задача. `шаги` — список (заголовок, сдвиг контроля в днях)."""
    данные = {
        "title": название,
        "tags": [МЕТКА] + теги,
        "body": тело,
        "steps": [{"title": t, "control_date": день(d).isoformat()} for t, d in шаги],
    }
    ответ = engine.cmd_create(_args(json=json.dumps(данные)), день(заведена))
    if not ответ.get("ok"):
        sys.exit(f"{название}: {ответ.get('errors')}")
    return название


def ход(команда, задача, шаг, когда, **поля):
    """Обычный исход по шагу, но датой из прошлого."""
    return команда(_args(task=задача, step=str(шаг), **поля), день(когда))


def наполнить():
    # 1. Буксует и просрочена: три переноса «не сделано» подряд — ровно тот
    #    случай, ради которого в ТЗ есть отдельная подсветка «буксует».
    t = завести("Согласовать смету с подрядчиком", ["стройка"],
                [("Получить смету по электрике", -12),
                 ("Свести с проектной и подписать", -4)],
                тело="Подрядчик тянет с электрикой третью неделю.", заведена=-14)
    for сдвиг in (-12, -9, -6):
        ход(engine.cmd_notdone, t, 1, сдвиг,
            reason="жду ответа от другого человека", to=день(сдвиг + 3).isoformat())

    # 2. Просрочена сильно, один шаг — как выглядит завал без истории.
    завести("Продлить страховку на технику", ["техника"],
            [("Запросить счёт у страховой", -9)], заведена=-11)

    # 3. Сегодня, утреннее время уже прошло — просрочка внутри дня.
    t = завести("Отправить акты за июль", ["бухгалтерия", "документы"],
                [("Подписать у директора", -3), ("Отвезти в бухгалтерию", 0)],
                заведена=-5)
    ход(engine.cmd_done, t, 1, -3)

    # 4. Сегодня, но вечером — впереди, а не просрочено.
    завести("Созвон с поставщиком щебня", ["закупки"],
            [("Позвонить, уточнить цену на сентябрь", 0)], заведена=-2)

    # 5. Многошаговая на середине: два шага закрыты, третий ждёт.
    t = завести("Нанять прораба на объект в Истре", ["найм", "стройка"],
                [("Составить требования", -8), ("Разместить вакансию", -6),
                 ("Провести три собеседования", 2), ("Оформить выход", 9)],
                тело="Кандидатов ищем через [[Василий Говнов]].", заведена=-10)
    ход(engine.cmd_done, t, 1, -8)
    ход(engine.cmd_done, t, 2, -5)

    # 6. Спокойно ждёт — большинство задач живут именно так.
    завести("Оплатить налоги за третий квартал", ["бухгалтерия"],
            [("Свериться с выпиской", 4), ("Заплатить", 11)], заведена=-1)

    # 7. Далеко впереди: проверяем, что лента такое не показывает.
    завести("Продлить аренду склада", ["аренда"],
            [("Написать арендодателю о ставке", 21),
             ("Подписать допсоглашение", 34)], заведена=-1)

    # 8. Закрыта целиком.
    t = завести("Заменить насос на объекте", ["техника", "стройка"],
                [("Заказать насос", -7), ("Смонтировать и проверить", -3)],
                заведена=-9)
    ход(engine.cmd_done, t, 1, -7)
    ход(engine.cmd_done, t, 2, -3)

    # 9. Отменена: файл и история остаются, из ленты уходит.
    t = завести("Купить второй бетононасос", ["техника"],
                [("Сравнить предложения", -2)], заведена=-6)
    ход(engine.cmd_cancel, t, 1, -2, reason="передумал, надо переформулировать")

    # 10. Провален шаг — задача идёт дальше. Не то же, что снят.
    t = завести("Получить разрешение на врезку", ["документы"],
                [("Подать через МФЦ", -6), ("Подать напрямую в водоканал", 1)],
                заведена=-8)
    ход(engine.cmd_fail, t, 1, -6, reason="внешние обстоятельства")

    # 11. Снят шаг — пошли другим путём.
    t = завести("Вывезти грунт с площадки", ["стройка"],
                [("Искать самосвал в аренду", -4), ("Забрать своим КамАЗом", 3)],
                заведена=-5)
    ход(engine.cmd_skip, t, 1, -4, reason="не было денег")

    # 12. Перенесена вручную — в журнале «перенесён», а не «не сделано».
    t = завести("Свести смету по фундаменту", ["стройка", "бухгалтерия"],
                [("Пересчитать объёмы бетона", 5)], заведена=-3)
    ход(engine.cmd_defer, t, 1, -1, to=день(5).isoformat(),
        reason="не хватило информации")

    # 13. Заметка с телефонами и ссылкой в базу — так поле body и используют.
    завести("Разобраться с долгом по субподряду", ["финансы"],
            [("Собрать акты и сверку", 1), ("Написать претензию", 6),
             ("Решить по суду или миром", 15)],
            тело="Сумма 840 тыс. Контакт: +7 900 000-00-00.\n"
                 "Юрист — [[Василий Говнов]], он же ведёт [[Заявка на грант ФПГ]].",
            заведена=-4)

    # 14. Задача с прошлым и будущим сразу: часть сделана, текущий просрочен.
    t = завести("Подготовить площадку к зиме", ["стройка"],
                [("Закрыть контур", -10), ("Проверить обогрев бытовок", -2),
                 ("Завезти реагент", 7)], заведена=-12)
    ход(engine.cmd_done, t, 1, -10)
    ход(engine.cmd_notdone, t, 2, -2, reason="не было времени", to=день(-1).isoformat())


ЗАМЕТКИ = {
    "Василий Говнов": ("люди", "Юрист и согласующий. Телефон и договор — заполнить."),
    "Заявка на грант ФПГ": ("документы", "Подана в июле, ждём решения комиссии."),
}


def заметки():
    """Пара записей базы знаний, чтобы ссылки [[...]] вели не в пустоту."""
    engine.KB_DIR.mkdir(parents=True, exist_ok=True)
    for имя, (тег, текст) in ЗАМЕТКИ.items():
        путь = engine.KB_DIR / f"{имя}.md"
        if путь.exists():
            continue
        путь.write_text(
            f"---\ntype: note\ntitle: {имя}\ntags: [{тег}, {МЕТКА}]\n---\n\n{текст}\n",
            encoding="utf-8")


def очистить():
    """Только своё: файл без тега «демо» не трогаем даже если он похож."""
    убрано = 0
    for task in engine.load_tasks():
        if МЕТКА in (task["meta"].get("tags") or []):
            task["path"].unlink()
            убрано += 1
    for имя in ЗАМЕТКИ:
        путь = engine.KB_DIR / f"{имя}.md"
        if путь.exists() and МЕТКА in путь.read_text(encoding="utf-8"):
            путь.unlink()
            убрано += 1
    return убрано


def main():
    ap = argparse.ArgumentParser(description="Тестовое наполнение вольта")
    ap.add_argument("--clean", action="store_true", dest="clean",
                    help="убрать задачи с тегом «демо» и вернуться к пустому вольту")
    args = ap.parse_args()

    if args.clean:
        print(f"убрано файлов: {очистить()}")
        return

    было = {t["path"].stem for t in engine.load_tasks()}
    заметки()
    наполнить()
    стало = engine.load_tasks()
    новых = [t for t in стало if t["path"].stem not in было]
    print(f"заведено задач: {len(новых)}, всего в вольте: {len(стало)}")
    print(f"вольт: {engine.VAULT}")
    print("убрать обратно: python3 demo.py --clean")


if __name__ == "__main__":
    main()
