#!/usr/bin/env python3
"""Файлы-вложения: картинки схем и прочие приложения к задаче или шагу.

В ТЗ этого требования нет — решение записано в `ПЛАН.md` («Вложения»,
обсуждение 2026-08-22). Метаданные лежат в `вольт.db` (таблица `attachments`,
`store.py`), сами байты — здесь, на диске рядом с базой, в папке `вложения/`.

Файл адресуется содержимым, не путём: имя на диске — sha256 плюс расширение
исходного имени. Одна и та же картинка, вставленная в две задачи, лежит одним
файлом; переименование или повторная загрузка того же файла не плодит копий.
Запись — во временный файл рядом и `replace()`, тот же приём, что у вольта:
оборванная запись не портит уже читаемый файл.

Владелец — задача или шаг, каждый со своей строкой в `attachments`
(`source_type`/`source_id`, по образцу `kb_links`). Запись базы знаний как
владелец — тоже в плане, но не сейчас: `Задачи/*.md`, — то есть `store.py` их
ещё нет, — они пока markdown-файлы с id по имени файла, а миграция таблицы
`kb_notes` в `ПЛАН.md` ещё не сделана (спринт 1, этап b). Адресовать вложение
именем файла, которое исчезнет при миграции, — переделка заранее; ждём этапа b.

В zip резервной копии байты не участвуют: `backup.py` пропускает эту папку
(`SKIP_DIRS`) — картинки не жмутся, а ротация N копий умножала бы их вес N раз.
Блобы неизменяемы по построению (адрес — хеш содержимого), поэтому бэкапу
хватает одного зеркала рядом с архивами, а не копии на каждую ротацию —
`backup.mirror_attachments` докладывает то, чего там ещё нет.
"""
import hashlib
import mimetypes
import re
from pathlib import Path
from urllib.parse import quote

DIR_NAME = "вложения"

# Разумный потолок для скриншота схемы или скана документа, не для видео —
# рабочая память сервера читает файл целиком, а не потоком.
MAX_BYTES = 15 * 1024 * 1024

# Отдаются в браузер как есть — контента, который браузер выполнил бы как код,
# у них не бывает. Всё остальное сервер отдаёт с Content-Disposition:
# attachment независимо от того, что написано в самом файле: HTML или SVG со
# скриптом внутри «безобидного» вложения не получает шанса исполниться в
# контексте страницы.
INLINE_SAFE = {"image/png", "image/jpeg", "image/gif", "image/webp", "application/pdf"}


class AttachmentError(Exception):
    def __init__(self, field, message):
        super().__init__(message)
        self.field = field
        self.message = message

    def as_json(self):
        return {"field": self.field, "error": self.message}


def dir_path(vault):
    return Path(vault) / DIR_NAME


def _ext(filename):
    """Расширение для имени на диске: только буквы и цифры после точки, не
    длиннее восьми символов. Идентичность файла — хеш, не имя; расширение
    нужно только чтобы Проводник и браузер угадали тип с первого взгляда."""
    suffix = Path(filename or "").suffix.lower()
    буквы = re.sub(r"[^a-z0-9]", "", suffix[1:])[:8]
    return f".{буквы}" if буквы else ""


def guess_mime(filename):
    тип, _ = mimetypes.guess_type(filename or "")
    return тип or "application/octet-stream"


def locate(vault, sha256):
    """Файл уже на диске по его хешу, независимо от того, каким именем его
    когда-то загрузили.

    Расширение — не часть идентичности, только украшение имени на диске:
    первая загрузка «схема.png» и вторая с тем же содержимым, но другим
    именем «то-же-самое.jpg», обязаны остаться одним файлом, а не превратить
    один и тот же кусок байтов в две копии на диске под разными хвостами.
    Поиск — по префиксу: sha256 фиксированной длины, поэтому один хеш не
    может оказаться префиксом другого, и подмены здесь нет.
    """
    d = dir_path(vault)
    if not d.is_dir():
        return None
    for f in d.iterdir():
        if f.is_file() and f.name.startswith(sha256):
            return f
    return None


def save(vault, data, filename):
    """Положить байты на диск под их хешем. Возвращает (sha256, размер).

    Файл с таким же содержимым уже на диске (под любым именем) — второй раз
    не пишем: это и есть дедупликация, не отдельная функция, а следствие
    того, что перед записью всегда сверяемся с `locate`, а не с путём,
    построенным из имени текущей загрузки.
    """
    if len(data) > MAX_BYTES:
        raise AttachmentError(
            "file", f"Файл больше {MAX_BYTES // (1024 * 1024)} МБ")
    sha256 = hashlib.sha256(data).hexdigest()
    if locate(vault, sha256) is None:
        путь = dir_path(vault) / f"{sha256}{_ext(filename)}"
        путь.parent.mkdir(parents=True, exist_ok=True)
        tmp = путь.with_name(путь.name + ".tmp")
        tmp.write_bytes(data)
        tmp.replace(путь)
    return sha256, len(data)


def content_type_and_disposition(mime, filename):
    """Заголовки для отдачи файла из `store.get_attachment`.

    Инлайновым типам — показ прямо в браузере с их настоящим типом; всё
    остальное — только на скачивание с общим `application/octet-stream`,
    независимо от того, что записано в базе как `mime`: запись в базе делает
    тот же `guess_mime` по имени файла, а имя файла — то, что ввёл человек,
    доверять ему как признаку безопасности нельзя.
    """
    имя = quote((filename or "файл").replace("\r", "").replace("\n", ""))
    if mime in INLINE_SAFE:
        return mime, f"inline; filename*=UTF-8''{имя}"
    return "application/octet-stream", f"attachment; filename*=UTF-8''{имя}"
