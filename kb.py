#!/usr/bin/env python3
"""Распознавание записей базы знаний в тексте. Требование R17, разделы 5.7, 5.8 и 7 ТЗ.

Модуль отвечает на один вопрос: какие куски текста похожи на упоминание записи базы
знаний и где именно они начинаются и кончаются. Смещения нужны интерфейсу, чтобы
подчеркнуть ровно найденное место, а не перекрашивать строку целиком.

Ссылку модуль не создаёт. `find_mentions` возвращает гипотезы с `confirmed: False`,
ссылкой гипотеза становится в `confirm()`, который зовут по кнопке «да» из окна
«Это Василий Говнов?». Так требует раздел 7.1: до ответа человека в базу не пишется
ничего. Проставленную автоматически ссылку заказчик через месяц не отличит от
поставленной руками, а разбирать чужие ошибки в своей базе он не подписывался.

Морфология на pymorphy3 (он в requirements.txt: 15 МБ словарей, чистый Python,
работает без сети). До него здесь стояло самодельное отсечение окончаний, и оно
путало словообразование с падежом. У «Грантовый» после среза «ый» оставалось ровно
«грантов» — слово из названия «Фонд президентских грантов», и запись предлагалась.
У «говновая» после среза «ая» оставалось «говнов», то есть фамилия из другой записи.
Ограничение на длину хвоста (не больше трёх букв) от этого не спасало: оба окончания
в него укладывались. Через разбор такого не выходит: у «грантовый» и «говновый»
нормальные формы свои собственные, с «грант» и «говнов» они не пересекаются.

Лучшую лемму модуль не выбирает — берётся множество нормальных форм слова и
пересекается со словарём известных названий. Так можно, потому что словарь закрытый:
угадывать, чем именно является «Говновым», незачем, достаточно попасть в известную
запись. На фамилиях лучший разбор как раз врёт — «Говнова» с весом 0,54 разбирается
как краткое прилагательное «говновый», а нужный «говнов» идёт следом с весом 0,15.

Со стороны словаря нормальные формы берутся не все, а только из разборов
«существительное в именительном единственного». Иначе название «Говнов» само
притащило бы за собой лемму «говновый» (тот же разбор в краткое прилагательное), и
«говновая контора» совпала бы с записью «Василий Говнов» — то есть ошибка вернулась бы
с другой стороны. Второй разбор, который этот фильтр отсекает, — родительный
множественного: без него «Иванов» тянет за собой лемму «иван», и запись «Иванов»
всплывала бы на слове «Ивану».

Названия из слов не в именительном («Фонд президентских грантов») под фильтр не
подходят вовсе, поэтому он отступает по ступеням: именительный единственного →
любое существительное → любой разбор. Последняя ступень нужна прилагательным в
названиях («президентских») и словам, которых в словаре нет.

Фамилий заказчика в словаре pymorphy3 нет, и это рабочий случай, а не сбой:
`word_is_known("говнов")` отвечает False, разбор идёт через предсказатель по
окончанию. Проверено на «Говнов»: предсказатель даёт разбор с пометкой Surn
(«говнов», sing, nomn) и вместе с ним мусорные варианты — краткое прилагательное
«говновый» и родительный множественного «говен». Модуль опирается именно на
Surn-гипотезу предсказателя, а мусор снимает фильтром по именительному
существительного. Падежи предсказанной фамилии разбираются верно: «Говнову»,
«Говновым», «Говнове», «Говновых» дают «говнов».

Точность важнее полноты (см. раздел 7.3): пропущенное упоминание заказчик поставит
руками, а на ложные ему придётся тыкать «нет» по десять раз в день, после чего он
выключит распознавание целиком.

Хранение отделено от расчёта: `LinkStore` и `ExclusionStore` знают, где лежат
подтверждённые ссылки и отказы, и не знают ни про морфологию, ни про смещения.
У наследника два метода про файлы (`_load`, `_commit`), поэтому переезд хранилища на
SQLite будет третьим наследником, а не правкой `find_mentions`.
"""
import json
import os
import re
import tempfile
import time
from collections import namedtuple
from datetime import datetime
from functools import lru_cache
from pathlib import Path

# Минимальная длина совпадения из раздела 7.3. Три буквы и меньше дают шум:
# «ФПГ» ещё можно узнать по регистру, а «дом» в тексте почти всегда просто дом.
MIN_MATCH = 4

# Слово короче трёх букв зацепкой не работает: «и» из «Иванов и партнёры» стоит в
# каждом тексте, а название всё равно подтвердится по соседнему слову.
MIN_HOOK = 3

# Диапазон а-я не включает «ё», а ASCII-класс \w в чужих примерах молча резал
# кириллицу пополам. Дефис в токен не входит: «Иванов-Петров» разбирается как два
# слова, и тогда склоняются обе половины.
TOKEN_RE = re.compile(r"[А-Яа-яЁёA-Za-z0-9]+")

# Служебные и частые слова из раздела 7.3. Запись из одного такого слова в
# распознавании не участвует вовсе, а внутри длинного названия слово остаётся —
# «Фонд президентских грантов» находится целиком, но по слову «на» не цепляется.
DEFAULT_STOPWORDS = frozenset({
    # предлоги, союзы, частицы
    "в", "во", "на", "за", "по", "до", "из", "от", "у", "к", "ко", "с", "со",
    "о", "об", "обо", "для", "при", "про", "над", "под", "без", "через", "между",
    "и", "а", "но", "или", "что", "чтобы", "как", "если", "когда", "тогда",
    "же", "ли", "бы", "не", "ни", "да", "нет", "вот", "уже", "еще", "только",
    "даже", "тоже", "также", "чем", "тем", "то",
    # местоимения
    "я", "ты", "он", "она", "оно", "мы", "вы", "они", "это", "этот", "эта", "эти",
    "тот", "та", "те", "свой", "наш", "ваш", "их", "его", "ее", "кто", "чей",
    "весь", "вся", "все", "сам", "такой", "который",
    # частые слова этого трекера: они встречаются в каждой второй задаче
    "задача", "шаг", "дело", "дата", "срок", "день", "неделя", "месяц", "год",
    "время", "вопрос", "ответ", "работа", "надо", "нужно", "сделать", "сделано",
    "отдать", "взять", "позвонить", "написать", "отправить", "проверить",
    "встреча", "звонок", "письмо", "документ", "файл", "папка", "номер",
    "сумма", "счет", "оплата", "оплатить", "договор", "деньги",
})

# Название или синоним записи, разобранные один раз при сборке индекса. Хранить
# разбор, а не пересчитывать на каждом тексте: индекс собирается при старте, а
# сканируют им каждую задачу в ленте.
Name = namedtuple("Name", "entry_id title text words forms kind")

_МОРФОЛОГ = None


def _морфолог():
    """MorphAnalyzer, созданный при первом разборе, а не при импорте.

    Замерено в свежем процессе: `import pymorphy3` — 20–30 мс, чтение 15 МБ
    словарей — 40–90 мс. `import kb` случается и там, где распознавание не нужно
    (например, ради `tokenize`), и платить эту сотню миллисекунд за каждый запуск
    командной строки незачем.
    """
    global _МОРФОЛОГ
    if _МОРФОЛОГ is None:
        import pymorphy3
        _МОРФОЛОГ = pymorphy3.MorphAnalyzer()
    return _МОРФОЛОГ


def normalize(word):
    """Регистр и «ё» в счёт не идут: заказчик пишет «говнову» и «ГОВНОВУ» вперемешку,
    а «Семёнов» в половине мест набран через «е»."""
    return word.lower().replace("ё", "е")


@lru_cache(maxsize=100_000)
def _parse(word):
    """Разбор слова с кэшем.

    Кэш здесь обязателен: первый разбор слова стоит около 50 мкс (и знакомого
    словарю, и предсказанного), повторный из кэша — доли микросекунды. Лента прогоняет
    через распознавание полсотни текстов подряд, где «отдать», «письмо» и фамилия
    заказчика встречаются десятками. Слово подаётся в нижнем регистре, но с «ё»:
    предсказатель по «Говнову» и «говнову» отвечает одинаково, а вот «ё» ему помогает.
    Ключ кэша — уже приведённое слово, иначе «ГОВНОВУ» и «Говнову» займут две ячейки.
    """
    return tuple(_морфолог().parse(word))


@lru_cache(maxsize=100_000)
def name_forms(word):
    """Нормальные формы слова из названия записи.

    Берутся разборы существительного в именительном единственного — в таком виде
    заказчик и пишет названия в базе. Фильтр держит два конкретных промаха разбора:
    краткое прилагательное («Говнов» → «говновый», после чего запись нашлась бы в
    слове «говновая») и родительный множественного («Иванов» → «иван», после чего
    запись нашлась бы в слове «Ивану»).

    Ступени отступления нужны словам названия, которые в именительном не стоят:
    у «грантов» из «Фонда президентских грантов» именительного разбора нет, зато
    есть существительное; у «президентских» нет и его, остаётся общий разбор.

    Само слово в множество кладётся всегда. Без него теряется, например, «Говнова»:
    предсказатель приводит женскую фамилию к мужской форме «говнов», и запись
    «Мария Говнова» перестала бы отличаться от «Василия Говнова».
    """
    слово = word.lower()
    разборы = _parse(слово)
    отобранные = [р for р in разборы
                  if р.tag.POS == "NOUN" and "nomn" in р.tag and "sing" in р.tag]
    if not отобранные:
        отобранные = [р for р in разборы if р.tag.POS == "NOUN"]
    if not отобранные:
        отобранные = разборы
    формы = {normalize(слово)}
    формы.update(normalize(р.normal_form) for р in отобранные)
    return frozenset(формы)


@lru_cache(maxsize=100_000)
def token_forms(word):
    """Нормальные формы слова из текста — все, какие даёт разбор, плюс само слово.

    Здесь фильтра по части речи нет намеренно: слово в тексте стоит в любом падеже,
    и отбор «именительный единственного» выбросил бы как раз то, ради чего разбор
    затевался. Лишние варианты не опасны, потому что сопоставляются они с закрытым
    словарём: «говновая» даёт только «говновый», а такой записи в базе нет.
    """
    слово = word.lower()
    формы = {normalize(слово)}
    формы.update(normalize(р.normal_form) for р in _parse(слово))
    return frozenset(формы)


def tokenize(text):
    """Слова текста со смещениями: [(слово, offset_start, offset_end)].

    Разбор по границам слов, а не поиск подстроки, закрывает главный источник
    ложных срабатываний: «Говнов» внутри «Говновский» подстрокой находится, а
    отдельным словом — нет.
    """
    return [(m.group(0), m.start(), m.end()) for m in TOKEN_RE.finditer(text or "")]


def _stop_forms(words):
    """Стоп-лист хранится нормальными формами: иначе «задача» в списке не поймает
    «задачи». Разбирается он как словарь, а не как текст: список написан в
    именительном, и лишние леммы вроде «деть» у слова «дело» тут ни к чему."""
    формы = set()
    for слово in words:
        формы |= name_forms(слово)
    return frozenset(формы)


def _is_stopword(word, stop):
    return bool(token_forms(word) & stop)


class Index:
    """Индекс названий и синонимов: нормальная форма → в каких названиях она стоит и
    на каком месте в них.

    Хранится индекс, чтобы не перебирать все записи по каждому слову. Замер на объёме
    из задания (500 записей, 1000 названий с синонимами, текст в 90 слов): перебор
    21,4 мс на текст, индекс 1,2 мс, разница в 18 раз. Одна задача откроется
    незаметно и так, но лента сканирует полсотни текстов подряд, и перебор
    превращается в секунду задумчивости на каждое обновление экрана.

    Худший случай индекса — слово, общее для сотен записей («партнёры» в синонимах):
    по нему приходится проверить все названия сразу. Замерено на базе, где общее
    слово стоит во всех 500 записях: 2,3 мс на текст. Ограничивать длину списка
    незачем, а вот стоп-лист такие слова гасит бесплатно.

    Сборка индекса на 500 записях стоит около 100 мс в свежем процессе, и большая
    часть этого времени — загрузка словарей pymorphy3, а не разбор названий. Цена
    разовая, при старте, и она же греет кэш разбора: первое сканирование текста
    после сборки укладывается в 2 мс, дальше 1,2 мс.
    """
    __slots__ = ("by_form", "solo_title", "solo_word", "names", "min_match",
                 "stopwords", "skipped")

    def __init__(self, min_match, stopwords):
        self.by_form = {}      # форма → [(Name, позиция слова в названии)]
        self.solo_title = set()  # формы, которые служат целым названием одной записи
        self.solo_word = set()   # формы, встречающиеся в названиях одной записи
        self.names = []
        self.min_match = min_match
        self.stopwords = stopwords
        self.skipped = []      # что в распознавании не участвует и почему

    def __len__(self):
        return len(self.names)


def _entry_id(entry):
    return entry.get("id") or (entry.get("title") or entry.get("name") or "").strip()


def _names_of(entry):
    """Название и синонимы записи одним списком. Синонимы заказчик ведёт сам
    (раздел 5.7), поэтому терпим и строку вместо списка, и лишние пробелы."""
    название = (entry.get("title") or entry.get("name") or "").strip()
    синонимы = entry.get("aliases") or entry.get("synonyms") or []
    if isinstance(синонимы, str):
        синонимы = [синонимы]
    пары = []
    if название:
        пары.append((название, "title"))
    for синоним in синонимы:
        синоним = (синоним or "").strip()
        if синоним:
            пары.append((синоним, "alias"))
    return название, пары


def build_index(entries, *, min_match=MIN_MATCH, stopwords=None):
    """Собрать индекс по записям базы знаний.

    Запись — словарь с `title` (или `name`), необязательными `aliases` (`synonyms`)
    и `id`. Всё, что в распознавании участвовать не может, не выбрасывается молча, а
    ложится в `index.skipped` с указанием поля: по КОНТРАКТу оболочка должна уметь
    показать, почему запись не подчёркивается, иначе это выглядит поломкой.
    """
    стоп = _stop_forms(DEFAULT_STOPWORDS if stopwords is None else stopwords)
    индекс = Index(min_match, стоп)
    держатели = {}   # форма → записи, в чьих названиях она встречается
    целиком = {}     # форма → записи, чьё название состоит из этого одного слова

    for запись in entries or ():
        ключ = _entry_id(запись)
        название, пары = _names_of(запись)
        if not название:
            индекс.skipped.append({"entry_id": ключ, "field": "title",
                                   "error": "нет названия"})
            continue
        for текст, вид in пары:
            слова = [w for w, _, _ in tokenize(текст)]
            if not слова:
                индекс.skipped.append({"entry_id": ключ, "field": вид, "value": текст,
                                       "error": "в названии нет слов"})
                continue
            # Раздел 7.3: запись из одного короткого слова в автораспознавании не
            # участвует. «АО» и «ИП» встречаются в каждой второй строке.
            if len(слова) == 1 and len(слова[0]) < min_match:
                индекс.skipped.append({"entry_id": ключ, "field": вид, "value": текст,
                                       "error": f"короче {min_match} символов"})
                continue
            if len(слова) == 1 and _is_stopword(слова[0], стоп):
                индекс.skipped.append({"entry_id": ключ, "field": вид, "value": текст,
                                       "error": "совпадает с частым словом"})
                continue

            имя = Name(entry_id=ключ, title=название, text=текст,
                       words=tuple(normalize(w) for w in слова),
                       forms=tuple(name_forms(w) for w in слова), kind=вид)
            индекс.names.append(имя)

            зацепок = 0
            for позиция, слово in enumerate(слова):
                # Зацепками работают только длинные незатёртые слова. По «и» из
                # «Иванов и партнёры» искать бессмысленно: оно есть в каждом тексте,
                # а название всё равно подтвердится по второму слову.
                if len(слово) < MIN_HOOK or _is_stopword(слово, стоп):
                    continue
                зацепок += 1
                for форма in имя.forms[позиция]:
                    индекс.by_form.setdefault(форма, []).append((имя, позиция))
                    if len(слово) >= min_match:
                        держатели.setdefault(форма, set()).add(ключ)
                        if len(слова) == 1:
                            целиком.setdefault(форма, set()).add(ключ)

            # Многословное название, у которого каждое слово либо короткое, либо
            # частое, зацепок не получает и поиском недостижимо. Раньше такая
            # запись оставалась в names и молча не находилась никогда — против
            # обещания докстроки, что непригодное попадает в skipped с полем.
            if not зацепок:
                индекс.names.pop()
                индекс.skipped.append({
                    "entry_id": ключ, "field": вид, "value": текст,
                    "error": "все слова названия слишком короткие или слишком частые",
                })

    # Опознавать запись по одному слову можно, только если это слово принадлежит
    # ровно одной записи. Есть «Василий Говнов» и «Мария Говнова» — по «Говнову»
    # вопрос «Это Василий Говнов?» задавать нечестно: ответ неизвестен и системе,
    # и человеку без остального текста.
    #
    # Счёт ведётся раздельно, потому что претензии на слово бывают разного веса.
    # «грантов» — это целая запись «Грант» и заодно третье слово «Фонда
    # президентских грантов». Спросить «Это Грант?» тут честно: слово совпало с
    # названием целиком, а у Фонда это только обрывок. Пока считалось одним
    # множеством, такое слово признавалось спорным и не находилось вообще.
    индекс.solo_title = {ф for ф, записи in целиком.items() if len(записи) == 1}
    индекс.solo_word = {ф for ф, записи in держатели.items() if len(записи) == 1}
    return индекс


def _aligned(name, forms_by_token, start):
    """Встают ли все слова названия подряд на слова текста, начиная с позиции start."""
    if start < 0 or start + len(name.words) > len(forms_by_token):
        return False
    for сдвиг, формы in enumerate(name.forms):
        if not (формы & forms_by_token[start + сдвиг]):
            return False
    return True


# Полное название вернее синонима, синоним вернее одного слова из названия.
# Порядок нужен, когда на одно место претендуют несколько гипотез.
_KIND_RANK = {"title": 0, "alias": 1, "part": 2}


def _hypothesis(name, text, start, end, kind):
    return {
        "entry_id": name.entry_id,
        "title": name.title,
        "via": name.text,
        "source": kind,
        "matched": text[start:end],
        "offset_start": start,
        "offset_end": end,
        "confirmed": False,
    }


def find_mentions(text, index, *, excluded=()):
    """Найти упоминания записей в тексте.

    Возвращает список гипотез, отсортированный по смещению. Каждая — словарь по
    разделу 5.8: `entry_id`, `title`, `via` (какое именно название сработало),
    `source`, `matched`, `offset_start`, `offset_end`, `confirmed: False`.
    Срез `text[offset_start:offset_end]` равен `matched` — интерфейс подчёркивает
    ровно это место.

    В базу не пишется ничего. Ссылка появляется в `confirm()`, и только оттуда.

    `excluded` — список исключений (ключи из `rejection_key` и `word_key`): то, на что
    человек уже ответил «нет». Без него отклонённое совпадение всплывает при каждом
    открытии задачи, и «нет» приходится жать бесконечно. Держит этот список
    `ExclusionStore`, но `find_mentions` про него не знает и принимает любое множество.
    """
    tokens = tokenize(text)
    if not tokens or not index.names:
        return []
    отказы = set(excluded)
    формы = [token_forms(слово) for слово, _, _ in tokens]

    найдено = {}
    for i, набор in enumerate(формы):
        зацепки = []
        for форма in набор:
            # Однозначность проверяется у той формы, которая связала слово с
            # названием, а не у слова целиком. У «Говнова» форм две: «говнова»
            # принадлежит одной Марии, «говнов» — и Марии, и Василию. Проверка по
            # слову целиком считала бы однозначным и второй случай, и по фамилии
            # всплывал бы Василий, которого в тексте нет.
            зацепки.extend((имя, позиция, форма in index.solo_title,
                            форма in index.solo_word)
                           for имя, позиция in index.by_form.get(форма, ()))
        for имя, позиция, целое_название, одна_запись in зацепки:
            if _aligned(имя, формы, i - позиция):
                # Название из одного слова опознаётся, только когда это слово не
                # служит целым названием ещё какой-нибудь записи.
                if len(имя.words) == 1 and not целое_название:
                    continue
                начало = i - позиция
                s = tokens[начало][1]
                e = tokens[начало + len(имя.words) - 1][2]
                _keep(найдено, _hypothesis(имя, text, s, e, имя.kind))
            elif len(имя.words) > 1 and одна_запись:
                # Из длинного названия сработало одно слово: «отдать Говнову денег»
                # про «Василия Говнова». Гипотеза слабее полной, поэтому она помечена
                # `part` и уступает любому совпадению подлиннее.
                s, e = tokens[i][1], tokens[i][2]
                if e - s >= index.min_match:
                    _keep(найдено, _hypothesis(имя, text, s, e, "part"))

    гипотезы = [г for г in найдено.values() if not _is_excluded(г, отказы)]
    return _resolve_overlaps(гипотезы)


def _keep(найдено, гипотеза):
    """На одно место от одной записи оставляем одну гипотезу — ту, что вернее."""
    ключ = (гипотеза["entry_id"], гипотеза["offset_start"], гипотеза["offset_end"])
    прежняя = найдено.get(ключ)
    вернее = прежняя is None or _KIND_RANK[гипотеза["source"]] < _KIND_RANK[прежняя["source"]]
    if вернее:
        найдено[ключ] = гипотеза


def _resolve_overlaps(гипотезы):
    """Пересекающиеся совпадения: длинное побеждает короткое (раздел 7.3).

    «Фонд президентских грантов» перекрывает запись «Грант» внутри себя. Показать
    оба — значит нарисовать подчёркивание внутри подчёркивания и спросить два раза
    про одно место.
    """
    гипотезы.sort(key=lambda г: (
        -(г["offset_end"] - г["offset_start"]),
        _KIND_RANK[г["source"]],
        г["offset_start"],
        str(г["entry_id"]),
    ))
    занято = []
    отобрано = []
    for г in гипотезы:
        s, e = г["offset_start"], г["offset_end"]
        if any(s < конец and начало < e for начало, конец in занято):
            continue
        занято.append((s, e))
        отобрано.append(г)
    отобрано.sort(key=lambda г: (г["offset_start"], г["offset_end"]))
    return отобрано


def rejection_key(mention):
    """Ключ для списка исключений: запись плюс само написание.

    По написанию, а не по смещению: смещения поедут при первой же правке текста, и
    отклонённое совпадение вернётся. Написание переживает правку соседнего слова.
    """
    return (mention["entry_id"], normalize(mention["matched"]))


def word_key(word):
    """Ключ исключения для слова целиком, без привязки к записи.

    Нужен там, где слово вообще не бывает ссылкой. «Грант» у заказчика чаще сумма
    денег, чем запись базы, и отказ по одной записи такое слово не гасит: оно тут же
    всплывает от соседней, и «нет» приходится жать по разу на каждую.
    """
    return (None, normalize(word))


def _is_excluded(mention, excluded):
    """Гипотеза отклонена, если совпал ключ по записи или ключ по слову целиком."""
    if not excluded:
        return False
    запись, написание = rejection_key(mention)
    return (запись, написание) in excluded or (None, написание) in excluded


def reject(mention, excluded=()):
    """Ответ «нет»: новый список исключений. Прежний не меняется — вызывающий сам
    решает, где его хранить."""
    return frozenset(excluded) | {rejection_key(mention)}


def confirm(mention, *, at=None):
    """Ответ «да»: гипотеза становится ссылкой. Единственное место, где это происходит.

    Возвращается новый словарь, исходная гипотеза не трогается: тот же список
    упоминаний интерфейс показывает дальше, и подтверждение одного не должно
    незаметно менять соседние.

    Повторное подтверждение возвращает ту же ссылку с прежним временем — по
    КОНТРАКТу операции идемпотентны, а оболочка вправе повторить запрос.
    """
    if mention.get("confirmed"):
        return dict(mention)
    ссылка = dict(mention)
    ссылка["confirmed"] = True
    ссылка["confirmed_at"] = (at or datetime.now()).isoformat(timespec="seconds")
    return ссылка


# --- хранение: раздел 5.8 ТЗ ------------------------------------------------

# Версия формата файлов. Пишется в них же: когда формат поменяется, читающий код
# увидит чужое число вместо того, чтобы разбирать файл наугад.
SCHEMA = 1

# Откуда пришёл текст, в котором нашлось упоминание. Список закрытый: по нему
# оболочка собирает блок «Упоминается в» (R3) и решает, что открыть по клику.
SOURCE_TYPES = ("task", "step", "reminder")


class KbError(Exception):
    """Ошибки идут списком с указанием поля — этого требует КОНТРАКТ. Форма подсветит
    все проблемные места сразу, бот соберёт их в фразу; строка «что-то не так» не
    годится ни тому, ни другому."""

    def __init__(self, errors):
        self.errors = list(errors)
        super().__init__("; ".join(f"{e['field']}: {e['error']}" for e in self.errors))


def validate_link(record):
    """Проверка ссылки по полям. Возвращает список ошибок целиком, а не первую
    попавшуюся: оболочке нужны все сразу."""
    errors = []
    if not record.get("kb_entry_id"):
        errors.append({"field": "kb_entry_id", "error": "нет записи базы знаний"})
    if record.get("source_type") not in SOURCE_TYPES:
        errors.append({"field": "source_type",
                       "error": "допустимо одно из: " + ", ".join(SOURCE_TYPES)})
    if not record.get("source_id"):
        errors.append({"field": "source_id", "error": "нет источника"})
    начало, конец = record.get("offset_start"), record.get("offset_end")
    if not isinstance(начало, int) or not isinstance(конец, int):
        errors.append({"field": "offset_start", "error": "смещения должны быть числами"})
    elif начало < 0:
        errors.append({"field": "offset_start", "error": "смещение отрицательное"})
    elif конец <= начало:
        errors.append({"field": "offset_end", "error": "конец раньше начала"})
    if not record.get("confirmed_at"):
        errors.append({"field": "confirmed_at", "error": "нет времени подтверждения"})
    return errors


def link_record(mention, *, source_type, source_id, at=None):
    """Подтверждённая ссылка в том виде, в каком она ложится в хранилище.

    Поля `kb_entry_id`, `source_type`, `source_id`, `offset_start`, `offset_end`,
    `confirmed_at` — из раздела 5.8 дословно, они же станут колонками таблицы, когда
    хранилище переедет на SQLite.

    Седьмое поле, `matched`, добавлено сверх списка. Смещения врут после первой же
    правки текста: дописал заказчик слово в начало названия шага, и подчёркивание
    уехало на соседнее. По сохранённому написанию оболочка находит место заново, а
    если не нашла — показывает ссылку в карточке без подчёркивания в тексте.

    Гипотеза подтверждается здесь же, через `confirm`: другого пути завести ссылку в
    модуле нет, и в обход подтверждения запись в хранилище не попадёт.
    """
    подтверждённая = confirm(mention, at=at)
    запись = {
        "kb_entry_id": подтверждённая["entry_id"],
        "source_type": source_type,
        "source_id": source_id,
        "offset_start": подтверждённая["offset_start"],
        "offset_end": подтверждённая["offset_end"],
        "confirmed_at": подтверждённая["confirmed_at"],
        "matched": подтверждённая["matched"],
    }
    errors = validate_link(запись)
    if errors:
        raise KbError(errors)
    return запись


def link_identity(record):
    """Что делает две ссылки одной и той же: запись, источник и место в нём.

    Время подтверждения в ключ не входит. Иначе повторное «да» после обрыва связи
    завело бы вторую ссылку на то же место, а по КОНТРАКТу операция идемпотентна.
    """
    return (record["kb_entry_id"], record["source_type"], str(record["source_id"]),
            record["offset_start"], record["offset_end"])


def _atomic_write(path, payload):
    """Запись через временный файл с заменой.

    Файл лежит в вольте, а вольт синхронизируется OneDrive и открыт в Obsidian.
    Дописывание на месте при обрыве даёт обрезанный файл, то есть потерю всех ссылок
    разом, а не одной.

    Повторы на PermissionError — из-за Windows: там os.replace ненадолго падает, если
    файл в этот момент держит антивирус или индексатор.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=str(path.parent), suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            # ensure_ascii=False — иначе русские названия лягут последовательностями
            # вида \u041a и починить файл в блокноте станет нельзя. Кодировка задана
            # явно: на Windows локаль не UTF-8.
            json.dump(payload, f, ensure_ascii=False, indent=1)
        for попытка in range(5):
            try:
                os.replace(tmp, path)
                break
            except PermissionError:
                if попытка == 4:
                    raise
                time.sleep(0.2 * (попытка + 1))
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


class LinkStore:
    """Склад подтверждённых ссылок: операции над ссылками и ничего про то, где они
    лежат.

    Наследник отвечает на два вопроса — как прочитать всё и как записать всё
    (`_load`, `_commit`). Ни `find_mentions`, ни `confirm` этого класса не видят, и
    сам он не знает про морфологию, поэтому переезд на SQLite ограничится третьим
    наследником.
    """

    def _load(self):
        raise NotImplementedError

    def _commit(self, links):
        raise NotImplementedError

    def all(self):
        return self._load()

    def add(self, mention, *, source_type, source_id, at=None):
        """Записать подтверждённую ссылку.

        Идемпотентно: вторая ссылка на то же место той же записи не заводится, и
        время подтверждения у неё остаётся первое. Оболочка вправе повторить запрос
        после обрыва связи, и повтор ничего не портит.
        """
        запись = link_record(mention, source_type=source_type,
                             source_id=source_id, at=at)
        текущие = self._load()
        ключ = link_identity(запись)
        for существующая in текущие:
            if link_identity(существующая) == ключ:
                return существующая
        текущие.append(запись)
        self._commit(текущие)
        return запись

    def for_source(self, source_type, source_id):
        """Ссылки одного текста — чтобы подчеркнуть в нём подтверждённые места."""
        return [ссылка for ссылка in self._load()
                if ссылка["source_type"] == source_type
                and str(ссылка["source_id"]) == str(source_id)]

    def for_entry(self, kb_entry_id):
        """Блок «Упоминается в» из R3: все задачи и шаги, где запись подтверждена."""
        return [ссылка for ссылка in self._load()
                if ссылка["kb_entry_id"] == kb_entry_id]

    def remove(self, record):
        """Снять ссылку. Снимать нечего — False, а не ошибка: повтор после обрыва
        не должен падать на втором заходе."""
        ключ = link_identity(record)
        текущие = self._load()
        осталось = [с for с in текущие if link_identity(с) != ключ]
        if len(осталось) == len(текущие):
            return False
        self._commit(осталось)
        return True

    def drop_source(self, source_type, source_id):
        """Забыть ссылки текста целиком: шаг удалили или переписали заново. Возвращает
        число снятых — оболочке есть что показать, а повтор вернёт ноль."""
        текущие = self._load()
        осталось = [с for с in текущие
                    if not (с["source_type"] == source_type
                            and str(с["source_id"]) == str(source_id))]
        снято = len(текущие) - len(осталось)
        if снято:
            self._commit(осталось)
        return снято


class MemoryLinkStore(LinkStore):
    """Хранение в памяти: для тестов и для предпросмотра. Копии наружу отдаются
    намеренно — иначе вызывающий поправит выданный словарь и незаметно изменит
    хранилище."""

    def __init__(self, links=()):
        self._links = [dict(с) for с in links]

    def _load(self):
        return [dict(с) for с in self._links]

    def _commit(self, links):
        self._links = [dict(с) for с in links]


class JsonLinkStore(LinkStore):
    """Хранение ссылок в одном JSON-файле вольта.

    JSON, а не заметка с frontmatter: файл целиком пишет программа, свободного текста,
    ради которого заказчик открыл бы его в Obsidian, в нём нет. Плоский список
    словарей с фиксированными полями ложится в таблицу SQLite один в один, поэтому
    переезд не потребует переразбора текста.
    """

    def __init__(self, vault):
        self.path = Path(vault) / "Ссылки.json"

    def _load(self):
        if not self.path.is_file():
            return []
        try:
            сырое = json.loads(self.path.read_text(encoding="utf-8"))
        except (ValueError, OSError) as e:
            # Битый файл не подменяется пустым списком: пустой список означал бы, что
            # первое же сохранение затрёт файл и все ссылки исчезнут насовсем. Лучше
            # отказаться работать и сказать, что именно не читается.
            raise KbError([{"field": None, "error": f"файл ссылок не читается: {e}"}])
        if not isinstance(сырое, dict) or not isinstance(сырое.get("links"), list):
            raise KbError([{"field": None, "error": "файл ссылок не в том формате"}])
        return сырое["links"]

    def _commit(self, links):
        _atomic_write(self.path, {"schema": SCHEMA, "links": links})


class ExclusionStore:
    """Склад отказов: то, что заказчик пометил как «не ссылка».

    Ключи здесь те же, какими `find_mentions` фильтрует гипотезы, поэтому
    `store.keys()` уходит прямо в `excluded=` без переупаковки. Отказ по одной
    записи — пара (запись, написание); отказ по слову целиком — пара (None,
    написание).
    """

    def _load(self):
        raise NotImplementedError

    def _commit(self, keys):
        raise NotImplementedError

    def keys(self):
        return frozenset(tuple(k) for k in self._load())

    def reject(self, mention):
        """Ответ «нет» на одну гипотезу. Повтор ничего не меняет и возвращает тот же
        ключ: кнопку «нет» жмут дважды чаще, чем кажется."""
        return self._add(rejection_key(mention))

    def mute_word(self, word):
        """«Это слово никогда не ссылка» — гасит его у всех записей разом."""
        return self._add(word_key(word))

    def forget(self, key):
        """Передумал: снять отказ, и совпадение снова начнёт предлагаться. Снимать
        нечего — False, а не ошибка."""
        ключ = tuple(key)
        текущие = self.keys()
        if ключ not in текущие:
            return False
        self._commit(текущие - {ключ})
        return True

    def _add(self, key):
        текущие = self.keys()
        if key not in текущие:
            self._commit(текущие | {key})
        return key


class MemoryExclusionStore(ExclusionStore):
    def __init__(self, keys=()):
        self._keys = {tuple(k) for k in keys}

    def _load(self):
        return set(self._keys)

    def _commit(self, keys):
        self._keys = {tuple(k) for k in keys}


class JsonExclusionStore(ExclusionStore):
    """Хранение отказов в файле вольта.

    Кортеж в JSON не выживает, поэтому ключ пишется словарём с именами полей:
    `{"kb_entry_id": ..., "text": ...}`, где `null` в первом поле означает «слово
    целиком, у любой записи». Читать такой файл глазами можно — а это тот самый файл,
    который заказчик откроет, когда случайно отклонит нужное совпадение.

    Список сортируется при записи: иначе файл в вольте меняется целиком при каждом
    сохранении, и OneDrive гоняет его туда-обратно на ровном месте.
    """

    def __init__(self, vault):
        self.path = Path(vault) / "Исключения.json"

    def _load(self):
        if not self.path.is_file():
            return set()
        try:
            сырое = json.loads(self.path.read_text(encoding="utf-8"))
        except (ValueError, OSError) as e:
            raise KbError([{"field": None,
                            "error": f"файл исключений не читается: {e}"}])
        if not isinstance(сырое, dict) or not isinstance(сырое.get("excluded"), list):
            raise KbError([{"field": None,
                            "error": "файл исключений не в том формате"}])
        return {(п.get("kb_entry_id"), п.get("text")) for п in сырое["excluded"]}

    def _commit(self, keys):
        строки = [{"kb_entry_id": запись, "text": написание}
                  for запись, написание in sorted(keys, key=lambda k: (str(k[0]), k[1]))]
        _atomic_write(self.path, {"schema": SCHEMA, "excluded": строки})
