"""Правила имени задачи и шаблона: предел длины, запрещённые символы, проверка.

Раньше константы жили в `engine.py`, а `templates.py` брал их оттуда, и через
это `core` не мог зависеть от `templates` без кольца `core → templates →
engine → core`. Здесь у правила один дом без зависимостей: движок, шаблоны и
`core` импортируют его, а не друг друга.
"""

# После переезда на SQLite название задачи больше не имя файла — ограничение
# сохранено, но теперь по другой причине. `|` занят синтаксисом piped-ссылок
# базы знаний (`[[Название|как написано]]`), `\/:*?"<>` в названии задачи
# нечитаемы и мешали бы будущим выгрузкам (Excel режет такие символы в именах
# листов). Осознанное продуктовое правило, не отпечаток файловой системы.
FORBIDDEN_IN_NAME = frozenset('\\/:*?"<>|')

# До 200 символов — раздел 6.3 ТЗ, число оттуда, не наша прикидка. Раньше здесь
# стояло 120 «пока экран не резиновый» — соображение о вёрстке ленты, подменившее
# собой число из требования. Вёрстку это не решало правильно: длинное название
# просто переносилось на несколько строк, а не переставало влезать совсем. Кому
# длинное название мешает — решает CSS обрезкой с многоточием (`.row-title` в
# feed.css), а не запрет заказчику назвать задачу подробно.
MAX_TITLE = 200


def title_error(title: str, existing_names) -> str | None:
    """Первая нарушенная проверка названия задачи или None, если название годится.

    Одна ошибка, а не список: правила исключают друг друга по смыслу (пустое
    название нечем сравнивать на дубль), и форме нужно одно сообщение под полем.
    `existing_names` — названия, с которыми сравнивать на совпадение без учёта
    регистра; вызывающий сам решает, исключать ли из них собственное название
    правящейся задачи.
    """
    title = (title or "").strip()
    if not title:
        return "Название задачи обязательно"
    if len(title) > MAX_TITLE:
        return f"Название длиннее {MAX_TITLE} символов"
    if set(title) & FORBIDDEN_IN_NAME:
        плохие = "".join(sorted(set(title) & FORBIDDEN_IN_NAME))
        return f"В названии нельзя символы {плохие}"
    if title.lower() in {n.lower() for n in existing_names}:
        return "Задача с таким названием уже есть"
    if title != title.strip(". "):
        return "Название не должно кончаться точкой или пробелом"
    return None
