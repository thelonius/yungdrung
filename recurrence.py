#!/usr/bin/env python3
"""Правила повторения. Требование R23, разделы 5.10–5.12 ТЗ.

Правило висит на шаблоне, задаче или напоминании и порождает череду экземпляров.
Здесь только календарная математика и решение «создавать или пропустить»: ни файлов,
ни базы, ни интерфейса. Смена хранилища этот код не тронет.

Главное правило, ради которого модуль вообще существует: **даты считаются от
календаря, а не от даты закрытия предыдущего цикла**. Если считать от закрытия,
«раз в месяц» превращается в «через месяц после того, как вспомнил», и за год
вместо двенадцати циклов выходит девять. Поэтому сетка дат строится от даты старта
правила (`start`), а факт закрытия влияет только на то, создавать ли очередной
экземпляр, — см. `due_cycles`.

Календарь считается здесь, а не через `dateutil.rrule`, хотя dateutil стоит и записан
в requirements.txt. Причина конкретная: RFC 5545 пропускает месяц, в котором заданного
числа нет, — правило «31-го числа» отдаёт за год одиннадцать циклов вместо двенадцати.
Нам нужен клампинг (31 февраля → 28-е, см. `_monthday`), а надстроить его над rrule
значит ловить каждый пропущенный месяц и досчитывать дату самим, то есть писать ту же
арифметику, что и здесь, плюс склейку двух источников дат и разбор, из какого источника
пришла каждая. `calendar.monthrange` закрывает это одной строкой.

Сама арифметика сверена с `dateutil.rrule` на шести тысячах случайных правил
daily/weekly/monthly — там, где трактовки совпадают, то есть без клампинга:
расхождений нет. Различается только годовое правило без `bymonth`, см. `_period_days`.

Слои намеренно разделены. Простые правила — «каждый день», «каждый вторник»,
«раз в месяц», «раз в квартал» — считаются без единого обращения к экзотике.
Вхождение в месяце (`bysetpos`), перенос с выходных (`holiday_shift`) и создание
заранее (`lead_days`) лежат отдельными функциями и включаются, только если поле
заполнено. Экзотику заказчик словами не подтверждал — вопрос Q26 в ТЗ, — и её можно
будет выкинуть, не трогая простой путь.

Порядок работы такой же, как у задач в engine.py: сначала `validate_rule`, потом всё
остальное. `normalize_rule` на неправильном правиле падает, а не считает молча.

  validate_rule(rule, start)                 список ошибок по полям
  preview(rule, start, count=5)              ближайшие даты для показа человеку
  next_dates(rule, start, count, since=...)  те же даты списком
  due_cycles(rule, start, now, previous=...) создавать очередной цикл или пропустить
  cycle_key(base)                            ключ цикла для журнала повторений

Ошибки — `RuleError` со списком полей, как того требует контракт, и `RuleExhausted`
для случая, когда поиск дат упёрся в предохранитель. Пустой список вместо ошибки
здесь запрещён: правило, которое молча перестало срабатывать, не заметит никто.
"""
