# --- ошибки -----------------------------------------------------------------

class RuleError(ValueError):
    """Ошибка правила со списком полей.

    Контракт требует структурных ошибок: форме надо подсветить конкретное поле,
    боту — собрать их в одну фразу. Поэтому исключение носит с собой тот же список
    словарей, что возвращает `validate_rule`, а не одну строку. Наследуется от
    ValueError, чтобы прежние `except ValueError` вокруг модуля продолжали ловить.
    """

    def __init__(self, errors):
        self.errors = [dict(e) for e in errors]
        super().__init__("; ".join(f"{e['field']}: {e['error']}" for e in self.errors))


class RuleExhausted(RuleError):
    """Поиск дат упёрся в предохранитель и нужного числа дат не набрал.

    Исключение, а не короткий список: правило, которое однажды молча перестало
    отдавать даты, в трекере не заметит никто, и человек будет ждать напоминания,
    которого не будет. Падение хотя бы видно.
    """


# --- разбор входных значений ------------------------------------------------

def as_date(value):
    """Дата из даты, момента или строки ISO. Время отбрасывается: правило
    повторения назначает день, а час контроля берётся из шаблона шага."""
    if isinstance(value, datetime):
        return value.date()
    if isinstance(value, date):
        return value
    if value is None:
        raise TypeError("дата не задана")
    return date.fromisoformat(str(value).strip())


def _numbers(value, field, allowed, hint, errors):
    """Поля-списки принимают и одиночное число: форма отдаёт список галочек,
    а из JSON и из CLI часто приходит скаляр, и падать на этом незачем."""
    if value is None or value == [] or value == ():
        return None
    items = list(value) if isinstance(value, (list, tuple, set)) else [value]
    собрано = []
    for v in items:
        if isinstance(v, bool) or not isinstance(v, int):
            errors.append({"field": field, "error": f"«{v}» — не число. {hint}"})
        elif v not in allowed:
            errors.append({"field": field, "error": f"{v} не подходит. {hint}"})
        else:
            собрано.append(v)
    return sorted(set(собрано)) or None


# --- проверка правила -------------------------------------------------------

def validate_rule(rule, start=None):
    """Проверка правила до сохранения. Возвращает список ошибок по полям.

    Ошибки списком, а не первым исключением: форма подсвечивает все проблемные
    поля разом, а бот собирает их в одну фразу. Так же устроен `validate_new_task`
    в engine.py, и расходиться этим двум местам нельзя.

    Помимо диапазонов проверяются сочетания. Человек, выбравший «месяц» и
    отметивший «вторник», почти наверняка имел в виду «второй вторник» и забыл
    указать номер вхождения; молча выдать ему все вторники месяца значит подсунуть
    недельное правило под видом месячного.
    """
    if not isinstance(rule, dict):
        return [{"field": "rule", "error": "Правило должно быть набором полей"}]

    errors = []

    freq = rule.get("freq")
    if not freq:
        errors.append({"field": "freq",
                       "error": "Выберите частоту: день, неделя, месяц или год"})
    elif freq not in FREQ:
        errors.append({"field": "freq",
                       "error": f"Частота «{freq}» неизвестна. Можно: {', '.join(FREQ)}"})
        freq = None

    interval = rule.get("interval")
    if interval is None:
        interval = 1
    if isinstance(interval, bool) or not isinstance(interval, int):
        errors.append({"field": "interval", "error": "«Каждые N» — целое число"})
    elif interval < 1:
        errors.append({"field": "interval", "error": "«Каждые N» начинается с единицы"})
    elif interval > MAX_INTERVAL:
        errors.append({"field": "interval",
                       "error": f"«Каждые {interval}» похоже на опечатку, предел {MAX_INTERVAL}"})

    byweekday = _numbers(
        rule.get("byweekday"), "byweekday", set(range(7)),
        "День недели — от 0 (понедельник) до 6 (воскресенье)", errors)
    bymonthday = _numbers(
        rule.get("bymonthday"), "bymonthday", set(range(1, 32)) | set(range(-31, 0)),
        "Число месяца — от 1 до 31; отрицательное считается с конца, -1 — последний день",
        errors)
    bysetpos = _numbers(
        rule.get("bysetpos"), "bysetpos", set(range(1, 6)) | set(range(-5, 0)),
        "Вхождение в месяце — от 1 до 5; отрицательное с конца, -1 — последнее", errors)
    bymonth = _numbers(
        rule.get("bymonth"), "bymonth", set(range(1, 13)), "Месяц — число от 1 до 12",
        errors)

    if freq in ("daily", "weekly"):
        месячные = (
            ("bymonthday", bymonthday, "Число месяца задают для месячного или годового правила"),
            ("bysetpos", bysetpos, "Вхождение в месяце задают для месячного или годового правила"),
            ("bymonth", bymonth, "Месяцы задают для месячного или годового правила"),
        )
        for поле, значение, текст in месячные:
            if значение:
                errors.append({"field": поле, "error": текст})
    if freq == "daily" and byweekday:
        errors.append({"field": "byweekday",
                       "error": "Дни недели задают для недельного правила"})
    if freq in ("monthly", "yearly"):
        if byweekday and bymonthday:
            errors.append({"field": "bymonthday",
                           "error": "Вместе с днём недели число месяца не задают, "
                                    "выберите что-то одно"})
        if byweekday and not bysetpos:
            errors.append({"field": "bysetpos",
                           "error": "Укажите, какое вхождение дня недели в месяце брать: "
                                    "1 — первое, 2 — второе, -1 — последнее"})
        if bysetpos and not byweekday:
            errors.append({"field": "byweekday",
                           "error": "Вхождение в месяце считается по дню недели, "
                                    "укажите день недели"})

    shift = rule.get("holiday_shift") or "none"
    if shift not in SHIFTS:
        errors.append({"field": "holiday_shift",
                       "error": "Перенос с выходного бывает none, before или after"})

    lead = rule.get("lead_days")
    if lead is None:
        lead = 0
    if isinstance(lead, bool) or not isinstance(lead, int):
        errors.append({"field": "lead_days", "error": "«Создавать за N дней» — целое число"})
    elif lead < 0:
        errors.append({"field": "lead_days",
                       "error": "«Создавать за N дней» не бывает отрицательным"})
    elif lead > MAX_LEAD:
        errors.append({"field": "lead_days",
                       "error": f"«Создавать за N дней» — не больше {MAX_LEAD}"})

    начало = None
    if start is not None:
        try:
            начало = as_date(start)
        except (ValueError, TypeError):
            errors.append({"field": "start",
                           "error": "Дату старта не понял, нужен формат 2026-08-17"})

    крайняя = None
    if rule.get("until") is not None:
        try:
            крайняя = as_date(rule["until"])
        except (ValueError, TypeError):
            errors.append({"field": "until",
                           "error": "Дату окончания не понял, нужен формат 2026-12-31"})
    if крайняя and начало and крайняя < начало:
        errors.append({"field": "until",
                       "error": "Правило кончается раньше, чем начинается"})

    if rule.get("paused") is not None and not isinstance(rule["paused"], bool):
        errors.append({"field": "paused", "error": "Приостановка — да или нет"})

    # Последняя проверка — даёт ли правило вообще хоть одну дату. По отдельности
    # каждое поле законно, а вместе они складываются в пустоту: «пятый вторник
    # февраля раз в четыре года» от 2026-го не сработает никогда, потому что 2026,
    # 2030, 2034 не високосные, а в 28-дневном феврале ровно четыре вторника.
    # Раньше такое правило проходило проверку, сохранялось и роняло генерацию дат
    # на «year 10002 is out of range» — то есть ошибка вылезала не там, где её
    # можно показать человеку. Проверка идёт по настройкам рабочего времени по
    # умолчанию: перенос с выходного дат не добавляет и не убирает, только двигает.
    if not errors and начало is not None:
        try:
            сетка = _occurrences(_normalized(rule), начало, 1, начало,
                                 worktime.settings())
        except RuleExhausted:
            сетка = []
        if not сетка:
            errors.append({
                "field": "until" if rule.get("until") is not None else "rule",
                "error": "Такое сочетание не даёт ни одной даты. Проверьте месяцы, "
                         "вхождение дня недели, «каждые N» и дату окончания",
            })

    return errors


def normalize_rule(rule, start=None):
    """Правило с подставленными значениями по умолчанию и списками вместо скаляров.

    Падает на неправильном правиле намеренно: считать даты по правилу, которое не
    прошло проверку, значит выдать человеку расписание, которого он не задавал.
    """
    ошибки = validate_rule(rule, start)
    if ошибки:
        raise RuleError(ошибки)
    return _normalized(rule)


def _normalized(rule):
    """Приведение полей к общему виду без проверки.

    Отдельно от `normalize_rule`, потому что проверка сама считает пробную дату и
    ей нужно приведённое правило. Вызов `normalize_rule` изнутри `validate_rule`
    зациклил бы их друг на друге.
    """
    пусто = []
    return {
        "freq": rule["freq"],
        "interval": rule.get("interval") or 1,
        "byweekday": _numbers(rule.get("byweekday"), "byweekday", set(range(7)), "", пусто),
        "bymonthday": _numbers(rule.get("bymonthday"), "bymonthday",
                               set(range(1, 32)) | set(range(-31, 0)), "", пусто),
        "bysetpos": _numbers(rule.get("bysetpos"), "bysetpos",
                             set(range(1, 6)) | set(range(-5, 0)), "", пусто),
        "bymonth": _numbers(rule.get("bymonth"), "bymonth", set(range(1, 13)), "", пусто),
        "holiday_shift": rule.get("holiday_shift") or "none",
        "lead_days": rule.get("lead_days") or 0,
        "until": as_date(rule["until"]) if rule.get("until") is not None else None,
        "paused": bool(rule.get("paused")),
    }


# --- простые правила: день, неделя, месяц, год ------------------------------

def _add_months(year, month, count):
    """Месяц через `count` месяцев. Считаем в номерах месяцев от нуля, потому что
    ручное «month + n, и если больше 12, то...» ошибается на границе декабря."""
    год, остаток = divmod(year * 12 + (month - 1) + count, 12)
    return год, остаток + 1


def _monthday(day, length):
    """Число месяца в конкретном месяце. Положительное считается от начала,
    отрицательное с конца: -1 даёт последний день.

    31-е в феврале превращается в 28-е (в високосный — в 29-е), а не пропадает.
    Стандарт RFC 5545 такой месяц пропустил бы, и «раз в месяц» дало бы за год
    одиннадцать циклов вместо двенадцати — заказчик заметил бы это только в марте.
    Решение спорное, оно вынесено в вопросы к ТЗ.
    """
    if day > 0:
        return min(day, length)
    return max(length + day + 1, 1)


def _month_days(year, month, rule, anchor):
    """Даты внутри одного месяца по правилу. Без переноса с выходных."""
    length = calendar.monthrange(year, month)[1]
    if rule["byweekday"] and rule["bysetpos"]:
        return _setpos_days(year, month, rule["byweekday"], rule["bysetpos"])
    if rule["bymonthday"]:
        return sorted({date(year, month, _monthday(d, length))
                       for d in rule["bymonthday"]})
    # Ничего не указано — держимся числа, с которого правило стартовало.
    return [date(year, month, _monthday(anchor.day, length))]


def _period_index(rule, anchor, day):
    """Номер периода, в который попадает день. Может быть отрицательным, если день
    раньше старта правила: деление берётся с округлением вниз, поэтому граница
    периода не съезжает."""
    freq, interval = rule["freq"], rule["interval"]
    if freq == "daily":
        return (day - anchor).days // interval
    if freq == "weekly":
        недель = ((day - timedelta(days=day.weekday()))
                  - (anchor - timedelta(days=anchor.weekday()))).days // 7
        return недель // interval
    if freq == "monthly":
        месяцев = (day.year - anchor.year) * 12 + (day.month - anchor.month)
        return месяцев // interval
    return (day.year - anchor.year) // interval


def _first_period(rule, anchor, since):
    """С какого периода начинать поиск, чтобы не пересчитывать всю историю правила.

    Предохранитель `MAX_PERIODS` считается отсюда, а не от старта: правило «каждый
    день», заведённое в 2020-м, к 2026 году набирает 2400 периодов и молча перестаёт
    отдавать даты. Отступ на `ЗАПАС_ДНЕЙ` назад нужен из-за переноса с выходного:
    цикл, чья расчётная дата чуть раньше отбора, после переноса вперёд может в отбор
    попасть.
    """
    return max(0, _period_index(rule, anchor, since - timedelta(days=ЗАПАС_ДНЕЙ)))


def _period_start(rule, anchor, k):
    """Первый календарный день k-го периода или None, если период выходит за
    границы календаря.

    Проверка границы живёт здесь, а не в `_period_days`: там дата уже строится, и
    правило «раз в четыре года» на 2400 периодов роняло генерацию с «year 10002 is
    out of range» вместо внятного ответа. Заодно это условие останова для поиска.
    """
    freq, interval = rule["freq"], rule["interval"]
    if freq == "daily":
        сдвиг = k * interval
        return anchor + timedelta(days=сдвиг) if сдвиг <= (date.max - anchor).days else None
    if freq == "weekly":
        понедельник = anchor - timedelta(days=anchor.weekday())
        сдвиг = k * interval * 7
        return понедельник + timedelta(days=сдвиг) \
            if сдвиг <= (date.max - понедельник).days else None
    if freq == "monthly":
        year, month = _add_months(anchor.year, anchor.month, k * interval)
        return date(year, month, 1) if year <= date.max.year else None
    year = anchor.year + k * interval
    return date(year, 1, 1) if year <= date.max.year else None


def _period_days(rule, anchor, k):
    """Даты k-го периода правила, по возрастанию. Перенос с выходных не применён.

    Периодом считается сутки, неделя, месяц или год — в зависимости от частоты,
    умноженные на «каждые N». Нулевой период содержит дату старта, поэтому сетка
    и привязана к календарю: сдвинуть её может только смена даты старта.
    """
    freq, interval = rule["freq"], rule["interval"]

    if freq == "daily":
        return [anchor + timedelta(days=k * interval)]

    if freq == "weekly":
        # От понедельника недели, в которую попал старт: иначе «по понедельникам
        # и четвергам» при старте в четверг дало бы понедельник следующей недели.
        начало_недели = anchor - timedelta(days=anchor.weekday())
        начало_недели += timedelta(weeks=k * interval)
        дни = rule["byweekday"] or [anchor.weekday()]
        return [начало_недели + timedelta(days=d) for d in дни]

    if freq == "monthly":
        year, month = _add_months(anchor.year, anchor.month, k * interval)
        if rule["bymonth"] and month not in rule["bymonth"]:
            return []
        return _month_days(year, month, rule, anchor)

    # Годовое правило без месяцев держится месяца старта: «второе воскресенье»
    # с началом 13 июля значит второе воскресенье июля, а не второе воскресенье
    # года. Здесь мы расходимся с RFC 5545 и с dateutil, которые без bymonth
    # считают вхождение по всему году и дали бы январь. Трактовка выбрана под
    # форму настройки: там человек задаёт дату старта и день недели, слова «год»
    # в смысле «отсчёт с 1 января» на экране нет.
    year = anchor.year + k * interval
    месяцы = rule["bymonth"] or [anchor.month]
    собрано = []
    for month in месяцы:
        собрано.extend(_month_days(year, month, rule, anchor))
    return sorted(собрано)


# --- экзотика: вхождение в месяце и перенос с выходных ----------------------

def _setpos_days(year, month, byweekday, bysetpos):
    """«Второй вторник» и «последняя пятница».

    Сначала выбираются все дни месяца с нужными днями недели, потом из этого
    списка берутся указанные позиции. Порядковый номер считается по месяцу, а не
    по неделям: «первый вторник» — это первый вторник числом, даже если первая
    неделя месяца началась в четверг.
    """
    length = calendar.monthrange(year, month)[1]
    подходящие = [date(year, month, d) for d in range(1, length + 1)
                  if date(year, month, d).weekday() in byweekday]
    собрано = []
    for pos in bysetpos:
        индекс = pos - 1 if pos > 0 else len(подходящие) + pos
        if 0 <= индекс < len(подходящие):
            собрано.append(подходящие[индекс])
    return sorted(set(собрано))


def shift_workday(day, mode="none", work=None):
    """Перенос даты с выходного вперёд или назад.

    Выходными считаются суббота и воскресенье: календарь государственных праздников
    в MVP не входит, и 12 июня правило воспримет как обычную пятницу. Признак
    выходного берётся из `worktime`, чтобы включённые выходные означали одно и то
    же и для уведомлений, и для повторений.

    «Последний рабочий день месяца» получается сложением двух полей: bymonthday=-1
    и holiday_shift=before. Отдельной логики под него нет.
    """
    if mode in (None, "none"):
        return day
    work = work or worktime.settings()
    шаг = 1 if mode == "after" else -1
    for _ in range(7):
        if worktime.is_workday(day, work):
            return day
        day += timedelta(days=шаг)
    return day


# --- генерация дат ----------------------------------------------------------

def _occurrences(rule, start, count, since, work, *, horizon=None):
    """Срабатывания правила: пары «расчётная дата — дата после переноса».

    Ограничитель ровно один из двух. `count` — набрать столько дат (превью и
    `next_dates`). `horizon` — идти до указанного дня и вернуть всё, что попало в
    окно (разбор циклов): там важно дойти до сегодняшнего дня, а не набрать число.

    Дедупликация обязательна: правило «22-е и 23-е числа с переносом вперёд» в
    августе 2026 даст понедельник 24-е дважды, и человек получит за один вечер
    два одинаковых вопроса.
    """
    собрано = []
    видели = set()
    # Отсечка по отбору включается, только если отбор сдвинут вперёд относительно
    # старта. Тогда он означает «циклы до сюда уже разобраны», и возвращаться туда
    # нельзя. На самом старте отсечки нет: перенос назад уводит первый цикл раньше
    # даты старта (1 августа — суббота, с holiday_shift=before это 31 июля), и цикл
    # от этого не исчезает, иначе август у человека просто пропадёт.
    порог = since if since > start else None
    первый = _first_period(rule, start, since)
    дошли = False
    for шаг in range(MAX_PERIODS):
        начало_периода = _period_start(rule, start, первый + шаг)
        if начало_периода is None:
            # Календарь кончился: дат после 9999 года не бывает. Для окна это
            # законный конец, для счёта — недобор, о нём ниже.
            дошли = horizon is not None
            break
        if horizon is not None and начало_периода > horizon + timedelta(days=ЗАПАС_ДНЕЙ):
            дошли = True
            break
        for база in _period_days(rule, start, первый + шаг):
            if база < start:
                continue  # первый период может начинаться раньше даты старта
            if rule["until"] and база > rule["until"]:
                return _sorted_occurrences(собрано, count)
            день = shift_workday(база, rule["holiday_shift"], work)
            if (порог and день < порог) or день in видели:
                continue
            видели.add(день)
            собрано.append({"base": база, "date": день})
        if count is not None and len(собрано) >= count:
            дошли = True
            break

    if not дошли:
        достигли = _period_start(rule, start, первый + MAX_PERIODS - 1)
        предел = f"до {достигли.isoformat()}" if достигли else "до конца календаря"
        if horizon is None:
            текст = (f"Правило не дало {count} дат: поиск дошёл {предел} и упёрся в "
                     f"предел в {MAX_PERIODS} периодов. Проверьте сочетание полей")
        else:
            текст = (f"Циклов накопилось больше, чем разбор берёт за раз: дошли "
                     f"{предел} при пределе в {MAX_PERIODS} периодов. Закройте "
                     f"предыдущий цикл или сдвиньте дату старта правила")
        raise RuleExhausted([{"field": "rule", "error": текст}])

    return _sorted_occurrences(собрано, count)


def _sorted_occurrences(собрано, count):
    """Даты по возрастанию. Сортировка нужна из-за переноса: цикл от 1 ноября с
    переносом назад встаёт на 30 октября, то есть раньше цикла от 1 ноября по
    порядку периодов."""
    собрано.sort(key=lambda o: (o["date"], o["base"]))
    return собрано[:count] if count is not None else собрано


def next_dates(rule, start, count=5, *, since=None, work=None):
    """Следующие `count` дат по правилу.

    `start` — дата старта правила и якорь календарной сетки. `since` — с какой даты
    отбирать; по умолчанию с самого старта. Разделение нужно ровно ради главного
    правила модуля: при работе движка `since` равен сегодняшнему дню, а сетка всё
    равно строится от `start`, поэтому пропущенный цикл не сдвигает следующие.
    """
    правило = normalize_rule(rule, start)
    начало = as_date(start)
    отбор = as_date(since) if since is not None else начало
    сетка = _occurrences(правило, начало, count, отбор, work or worktime.settings())
    return [o["date"] for o in сетка]


def create_at(day, rule):
    """Когда создавать экземпляр: за `lead_days` до расчётной даты.

    Отсчёт от даты после переноса, а не до него: человеку нужен запас перед тем
    днём, когда он реально будет делать дело.
    """
    дней = rule.get("lead_days") or 0
    return day - timedelta(days=дней)


def _ddmm(day):
    """Дата в том виде, в каком она стоит в уведомлениях ТЗ: «Цикл от 05.09»."""
    return f"{day.day:02d}.{day.month:02d}"


def preview(rule, start, count=5, *, since=None, work=None):
    """Ближайшие даты для показа человеку до сохранения правила.

    ТЗ (R23) требует превью минимум пяти дат, пересчитываемое на каждое изменение
    поля. Возвращаются и расчётная дата, и дата после переноса: иначе человек не
    поймёт, почему «последний день месяца» показывает 30 января.

    Правило перед вызовом должно пройти `validate_rule`: на полузаполненной форме
    считать нечего, там показывают ошибки, а не даты.
    """
    правило = normalize_rule(rule, start)
    начало = as_date(start)
    отбор = as_date(since) if since is not None else начало
    сетка = _occurrences(правило, начало, count, отбор, work or worktime.settings())

    строки = []
    for o in сетка:
        перенос = o["base"] if o["base"] != o["date"] else None
        создание = create_at(o["date"], правило)
        текст = f"{_ddmm(o['date'])} ({ДНИ_КОРОТКО[o['date'].weekday()]})"
        if перенос:
            текст += f", перенос с {_ddmm(перенос)}"
        if создание != o["date"]:
            текст += f", создать {_ddmm(создание)}"
        строки.append({
            "date": o["date"],
            "base": o["base"],
            "shifted_from": перенос,
            "create_at": создание,
            "weekday": ДНИ_КОРОТКО[o["date"].weekday()],
            "text": текст,
        })
    return строки


# --- циклы: создавать или пропустить ---------------------------------------

def cycle_key(base):
    """Стабильный ключ цикла: расчётная дата по календарной сетке, в ISO.

    Ключ нужен журналу повторений, чтобы отличить уже записанный цикл от нового.
    Пока предыдущий цикл не закрыт, один и тот же пропуск возвращается при каждом
    запуске — это правильно, человек должен видеть его в разборе, — но записать
    его в журнал надо один раз, а не тридцать за месяц простоя.

    Берётся дата **до** переноса с выходного: она зависит только от правила и даты
    старта, поэтому включённая в настройках суббота не переименует старые циклы.
    Ключ уникален в пределах одного правила: чьё это правило, знает вызывающий.
    """
    return base.isoformat()


def _previous_cycle(previous):
    """Предыдущий экземпляр правила в разобранном виде.

    Проверка отдельной функцией ради ошибки с полем: раньше `previous` без ключа
    `date` давал KeyError, а оболочке из KeyError показать человеку нечего.
    """
    if previous is None:
        return None
    if not isinstance(previous, dict):
        raise RuleError([{"field": "previous",
                          "error": "Предыдущий цикл описывается полями, среди них дата"}])
    if previous.get("date") is None:
        raise RuleError([{"field": "previous.date",
                          "error": "У предыдущего цикла нет даты, "
                                   "не от чего считать блокировку"}])
    try:
        дата = as_date(previous["date"])
    except (ValueError, TypeError):
        raise RuleError([{"field": "previous.date",
                          "error": "Дату предыдущего цикла не понял, "
                                   "нужен формат 2026-08-17"}]) from None
    return {"date": дата, "closed": bool(previous.get("closed"))}


def _trim_decisions(решения, limit):
    """Обрезка длинного разбора: лимит режет середину списка пропусков.

    Резать с конца нельзя. Пропуск не закрывает предыдущий цикл, поэтому назавтра
    вернётся ровно та же дюжина самых старых записей, и до свежих циклов очередь
    не дойдёт никогда: недельное правило с января к августу так и показывало март.
    Создания не режутся вовсе — это единственное решение, по которому оболочка
    заводит задачу.
    """
    if not limit or len(решения) <= limit:
        return решения
    созданные = [р for р in решения if р["action"] == "create"]
    место = max(limit - len(созданные), 0)
    пропуски = [р for р in решения if р["action"] != "create"]
    оставлено = созданные + (пропуски[-место:] if место else [])
    оставлено.sort(key=lambda р: (р["date"], р["base"]))
    return оставлено


def due_cycles(rule, start, now, *, previous=None, work=None, force=False, limit=12):
    """Что делать с циклами, до которых дошло время. Раздел 5.12 ТЗ.

    `previous` — предыдущий экземпляр правила: `{"date": ..., "closed": bool}` или
    None, если правило ещё ни разу не срабатывало. `now` — сегодняшняя дата.

    Незакрытый предыдущий экземпляр блокирует создание нового: вместо задачи
    пишется пропуск. Так требует ТЗ, и оно же предупреждает, чем это опасно —
    незакрытая августовская декларация утащит за собой сентябрьскую (вопрос Q22).
    Отсюда `force`: кнопка «Всё равно создать» отдаёт сюда True. Кнопка эта висит
    на уведомлении про один конкретный цикл, поэтому и создаётся один: следующие
    упираются уже в него. Иначе одно нажатие заводило бы разом все накопившиеся.

    Пропущенный цикл ничего не сдвигает. Даты следующих считаются от той же
    календарной сетки, поэтому «раз в месяц 5-го» останется пятым числом, сколько
    бы циклов подряд ни пропустили.

    Возвращается список решений по возрастанию дат: компьютер мог простоять
    выключенным три месяца, и каждый пропущенный цикл идёт в журнал повторений
    отдельной записью. Разбор всегда доходит до сегодняшнего дня; `limit`
    ограничивает длину ответа, вырезая середину, — см. `_trim_decisions`.

    Каждое решение несёт `key` — стабильный ключ цикла для журнала. Записи для
    одного и того же цикла в разные дни совпадают целиком, поэтому повторный
    вызов ничего не портит: этого требует раздел контракта про идемпотентность.
    """
    правило = normalize_rule(rule, start)
    if правило["paused"]:
        return []  # приостановленное правило не срабатывает и в журнал не пишет

    начало = as_date(start)
    сегодня = as_date(now)
    предыдущий = _previous_cycle(previous)

    отбор = предыдущий["date"] + timedelta(days=1) if предыдущий else начало
    # Горизонт по дате цикла, а не по дате создания: экземпляр с заделом заводится
    # раньше своего дня, поэтому окно шире на те же lead_days.
    горизонт = сегодня + timedelta(days=правило["lead_days"])
    сетка = _occurrences(правило, начало, None, отбор,
                         work or worktime.settings(), horizon=горизонт)

    осталось_принудительно = bool(force)
    решения = []
    for o in сетка:
        день, база = o["date"], o["base"]
        когда_создавать = create_at(день, правило)
        if когда_создавать > сегодня:
            break  # до этого цикла ещё не дошло время

        блокирует = предыдущий if (предыдущий and not предыдущий["closed"]) else None
        if блокирует and not осталось_принудительно:
            решения.append({
                "action": "skip",
                "key": cycle_key(база),
                "date": день,
                "base": база,
                "create_at": когда_создавать,
                "blocked_by": блокирует["date"],
                "message": (f"Цикл от {_ddmm(день)} пропущен: "
                            f"задача от {_ddmm(блокирует['date'])} не закрыта"),
            })
            continue
        решения.append({
            "action": "create",
            "key": cycle_key(база),
            "date": день,
            "base": база,
            "create_at": когда_создавать,
            "blocked_by": None,
            "message": f"Создан цикл от {_ddmm(день)}",
        })
        # Только что созданный экземпляр закрытым не бывает, поэтому следующий
        # цикл в этой же пачке упрётся в него и уйдёт в пропуск.
        предыдущий = {"date": день, "closed": False}
        # Кнопка «Всё равно создать» висит на уведомлении про один конкретный цикл,
        # значит и создать должна один. Раньше флаг гасился только внутри ветки
        # блокировки, а первое создание шло мимо неё: при закрытом предыдущем цикле
        # одно нажатие давало две задачи.
        осталось_принудительно = False

    return _trim_decisions(решения, limit)


# --- человеческое описание правила -----------------------------------------

def _plural(n, one, few, many):
    хвост = abs(n) % 100
    if 11 <= хвост <= 14:
        return many
    хвост %= 10
    if хвост == 1:
        return one
    if 2 <= хвост <= 4:
        return few
    return many


def _nth_weekday(pos, weekday):
    слова = ПОРЯДКОВЫЕ.get(pos)
    if слова:
        return f"{слова[РОД_ДНЯ[weekday]]} {ДНИ_ИМЕНИТЕЛЬНЫЙ[weekday]}"
    return f"{abs(pos)}-й с конца {ДНИ_ИМЕНИТЕЛЬНЫЙ[weekday]}"


def describe(rule):
    """Короткая подпись правила для шапки превью.

    Нужна затем, что список из пяти дат сам по себе не отвечает на вопрос «а что
    я, собственно, задал»: 08.09, 13.10, 10.11 выглядит случайным набором, пока
    рядом не написано «второй вторник месяца».
    """
    правило = normalize_rule(rule)
    freq, n = правило["freq"], правило["interval"]

    if freq == "daily":
        основа = "каждый день" if n == 1 else \
            f"каждые {n} {_plural(n, 'день', 'дня', 'дней')}"
    elif freq == "weekly":
        дни = правило["byweekday"]
        основа = "каждую неделю" if n == 1 else \
            f"каждые {n} {_plural(n, 'неделю', 'недели', 'недель')}"
        if дни:
            основа += " по " + ", ".join(ДНИ_ДАТЕЛЬНЫЙ[d] for d in дни)
    elif freq == "monthly":
        if n == 1:
            основа = "раз в месяц"
        elif n == 3:
            основа = "раз в квартал"
        else:
            основа = f"раз в {n} {_plural(n, 'месяц', 'месяца', 'месяцев')}"
        хвост = _days_caption(правило)
        if хвост:
            основа += ", " + хвост
    else:
        основа = "раз в год" if n == 1 else \
            f"раз в {n} {_plural(n, 'год', 'года', 'лет')}"
        хвост = _days_caption(правило)
        if хвост:
            основа += ", " + хвост

    if правило["holiday_shift"] == "before":
        основа += "; с выходного — на предыдущий рабочий день"
    elif правило["holiday_shift"] == "after":
        основа += "; с выходного — на следующий рабочий день"
    if правило["lead_days"]:
        д = правило["lead_days"]
        основа += f"; создавать за {д} {_plural(д, 'день', 'дня', 'дней')}"
    if правило["until"]:
        основа += f"; до {_ddmm(правило['until'])}.{правило['until'].year}"
    if правило["paused"]:
        основа += "; приостановлено"
    return основа


def _days_caption(rule):
    """Часть подписи про месяцы и дни. Пустая строка означает «держимся числа,
    с которого правило стартовало»: писать это словами незачем, дата старта
    и так стоит рядом в форме.

    Месяцы называются обязательно. Правило «15-го числа в марте и сентябре»
    описывалось как «раз в год, числа: 15», и по такой подписи проверить, то ли
    задано, нельзя: месяцы из неё выпадали целиком.
    """
    части = []
    if rule["bymonth"]:
        части.append("в " + ", ".join(МЕСЯЦЫ_ПРЕДЛОЖНЫЙ[m - 1] for m in rule["bymonth"]))
    if rule["bysetpos"] and rule["byweekday"]:
        части.append(_setpos_caption(rule["bysetpos"], rule["byweekday"]))
    elif rule["bymonthday"]:
        части.append(_monthdays_caption(rule["bymonthday"]))
    return ", ".join(части)


def _monthdays_caption(дни):
    """Числа месяца словами.

    Отрицательные числа расшифровываются: подпись «числа: -1, 1» заказчику не
    говорит ничего, а правило при этом срабатывает первого числа и в последний
    день месяца. Положительные идут первыми, отрицательные следом — в том же
    порядке, в каком выпадают даты.
    """
    части = []
    числа = [d for d in дни if d > 0]
    if числа:
        части.append("числа: " + ", ".join(str(d) for d in числа))
    for d in sorted(d for d in дни if d < 0):
        части.append(ДНИ_С_КОНЦА.get(d, f"{abs(d)}-й день с конца месяца"))
    return ", ".join(части)


def _setpos_caption(bysetpos, byweekday):
    """Подпись вхождения дня недели в месяце.

    Один день недели — «второй вторник»: позиция считается по вторникам, подпись
    совпадает с расчётом. Несколько дней недели считаются иначе: позиция берётся
    по общему списку, и последний из понедельников и пятниц — одна дата в месяце.
    Прежняя подпись перечисляла тут «последний понедельник, последняя пятница»,
    то есть обещала две даты вместо одной, а подпись — единственное, по чему
    человек проверяет правило перед сохранением.
    """
    bysetpos = _по_календарю(bysetpos)
    if len(byweekday) == 1:
        return ", ".join(_nth_weekday(p, byweekday[0]) for p in bysetpos)
    порядки = " и ".join(_nth_masculine(p) for p in bysetpos)
    дни = ", ".join(ДНИ_ИМЕНИТЕЛЬНЫЙ[d] for d in byweekday)
    return f"{порядки} из дней недели: {дни}"


def _по_календарю(bysetpos):
    """Вхождения в том порядке, в каком они выпадают в месяце.

    `normalize_rule` сортирует поле как числа, и -1 встаёт раньше 1. Подпись от
    этого читалась задом наперёд: «последний вторник, первый вторник» при датах
    01.09 и 29.09. Сначала счёт от начала месяца, потом с конца.
    """
    return sorted(bysetpos, key=lambda p: (p < 0, p))


def _nth_masculine(pos):
    """Порядковый номер вхождения в мужском роде — он согласуется со словом «день»
    в обороте «последний из дней недели»."""
    слова = ПОРЯДКОВЫЕ.get(pos)
    return слова[0] if слова else f"{abs(pos)}-й с конца"


# --- разбор человеческого текста --------------------------------------------
#
# Обратная сторона `describe`: «каждый вторник» → правило. Форма из четырёх
# селекторов проигрывает одной строке — график заказчик и так описывает словами,
# а не полями, и «последний рабочий день месяца» набрать быстрее, чем собрать из
# «число месяца = -1» и «перенос = назад».
#
# Без модели, и это не экономия. «Каждый второй вторник месяца» — словарь на два
# десятка слов, а не связная речь, то есть наша сторона границы из CLAUDE.md.
# LLM здесь означала бы сетевой вызов на каждое нажатие клавиши, невоспроизводимый
# ответ и неработающий без сети трекер (R6) — причём детерминированный разбор
# всё равно пришлось бы написать запасным путём.
#
# Правильность стережёт тождество `parse_text(describe(rule)) == rule`: две
# функции обязаны быть обратными друг другу, и тест гоняет его на случайных
# правилах. Поэтому словарь ниже покрывает ровно то, что печатает `describe`,
# плюс обиходные синонимы («ежемесячно», «по вторникам», «раз в две недели»).

# Основы слов вместо полных форм: русская морфология даёт «вторник», «вторника»,
# «вторникам», и держать все падежи списком — верный способ забыть один. Основа
# сравнивается началом слова, побеждает самая длинная: «пятницам» — день недели
# (основа «пятниц»), а «пятое» — порядковый номер (основа «пят»).
# Основа воскресенья кончается на «-сен», а не «-сень»: родительный
# множественного даёт «воскресений», и мягкий знак в основе его теряет.
ОСНОВЫ_ДНЕЙ = {"понедельник": 0, "вторник": 1, "сред": 2, "четверг": 3,
               "пятниц": 4, "суббот": 5, "воскресен": 6}
# Сокращения — только точным совпадением: «вс» началом слова поймало бы «всегда».
ТОЧНЫЕ_ДНИ = {к: i for i, к in enumerate(ДНИ_КОРОТКО)}

ОСНОВЫ_ПОРЯДКОВЫХ = {"перв": 1, "втор": 2, "трет": 3, "четверт": 4, "пят": 5,
                     "предпоследн": -2, "последн": -1}

ОСНОВЫ_МЕСЯЦЕВ = {"январ": 1, "феврал": 2, "март": 3, "апрел": 4, "июн": 6,
                  "июл": 7, "август": 8, "сентябр": 9, "октябр": 10,
                  "ноябр": 11, "декабр": 12}
# Май отдельно: основа «ма» подошла бы и к «марту», а короче её не сделать.
ТОЧНЫЕ_МЕСЯЦЫ = {"май": 5, "мая": 5, "мае": 5, "маю": 5, "маем": 5}

# Слово периода → частота. «Квартал» разворачивается в месяц с шагом три —
# отдельной частоты для него нет ни в RFC 5545, ни у нас.
ТОЧНЫЕ_ПЕРИОДЫ = {"день": "daily", "дня": "daily", "дней": "daily",
                  "сутки": "daily", "суток": "daily",
                  "год": "yearly", "года": "yearly", "году": "yearly",
                  "лет": "yearly"}
ОСНОВЫ_ПЕРИОДОВ = {"недел": "weekly", "месяц": "monthly", "квартал": "quarterly"}

# «Ежемесячно» несёт и частоту, и шаг разом, поэтому стоит отдельным словарём.
НАРЕЧИЯ = {"ежедневно": ("daily", 1), "еженедельно": ("weekly", 1),
           "ежемесячно": ("monthly", 1), "ежеквартально": ("monthly", 3),
           "ежегодно": ("yearly", 1)}

ЧИСЛИТЕЛЬНЫЕ = {"один": 1, "одну": 1, "два": 2, "две": 2, "три": 3, "четыре": 4,
                "пять": 5, "шесть": 6, "семь": 7, "восемь": 8, "девять": 9,
                "десять": 10, "полтора": 1}

# Слова про число месяца: «5 числа», «числа: 5, 15».
ОСНОВЫ_ЧИСЛА_МЕСЯЦА = ("числ",)


def _основа(token, словарь):
    """Значение по самой длинной подходящей основе. Длина решает споры вроде
    «пятницам» (день недели) против «пятое» (порядковое)."""
    лучшая = None
    for основа, значение in словарь.items():
        if token.startswith(основа):
            if лучшая is None or len(основа) > len(лучшая[0]):
                лучшая = (основа, значение)
    return лучшая[1] if лучшая else None


def _вид_слова(token):
    """Слово → (вид, значение). Вид: day, ordinal, month, period, adverb,
    number, monthday-marker или None для служебного мусора.

    Разбор идёт по одному слову, а не регуляркой на всю строку: порядок слов в
    живой речи не фиксирован («по вторникам каждую неделю» и «каждую неделю по
    вторникам» — одно и то же), и грамматика, которая на это опирается, ломается
    на первой же перестановке.
    """
    if token in ТОЧНЫЕ_ДНИ:
        return "day", ТОЧНЫЕ_ДНИ[token]
    if token in ТОЧНЫЕ_МЕСЯЦЫ:
        return "month", ТОЧНЫЕ_МЕСЯЦЫ[token]
    if token in ТОЧНЫЕ_ПЕРИОДЫ:
        return "period", ТОЧНЫЕ_ПЕРИОДЫ[token]
    if token in НАРЕЧИЯ:
        return "adverb", НАРЕЧИЯ[token]
    if token in ЧИСЛИТЕЛЬНЫЕ:
        return "number", ЧИСЛИТЕЛЬНЫЕ[token]
    if token.isdigit():
        return "number", int(token)

    # Дни недели проверяются раньше порядковых: основы у них длиннее и
    # конкретнее, иначе «пятницам» уехало бы в «пятое».
    for вид, словарь in (("day", ОСНОВЫ_ДНЕЙ), ("month", ОСНОВЫ_МЕСЯЦЕВ),
                         ("period", ОСНОВЫ_ПЕРИОДОВ), ("ordinal", ОСНОВЫ_ПОРЯДКОВЫХ)):
        значение = _основа(token, словарь)
        if значение is not None:
            return вид, значение
    if any(token.startswith(о) for о in ОСНОВЫ_ЧИСЛА_МЕСЯЦА):
        return "monthday-marker", None
    return None, None


def _срезать(текст, шаблон, действие, состояние):
    """Найти оговорку, отдать её `действию` и вырезать из строки.

    Оговорки снимаются до разбора основной части, иначе «создавать за 3 дня»
    объявило бы правило ежедневным: слово «дня» в нём то же самое.
    """
    m = re.search(шаблон, текст)
    if not m:
        return текст
    действие(m, состояние)
    return (текст[:m.start()] + " " + текст[m.end():]).strip()


def _дата_из_текста(s):
    """Дата из «31.12.2026», «31.12» или «2026-12-31». Год по умолчанию нужен
    только `until`, а там он всегда написан — `describe` его печатает."""
    s = s.strip()
    m = re.fullmatch(r"(\d{4})-(\d{2})-(\d{2})", s)
    if m:
        return date(int(m.group(1)), int(m.group(2)), int(m.group(3)))
    m = re.fullmatch(r"(\d{1,2})[.\-/](\d{1,2})[.\-/](\d{2,4})", s)
    if m:
        год = int(m.group(3))
        return date(год + 2000 if год < 100 else год, int(m.group(2)), int(m.group(1)))
    return None


def parse_text(text):
    """Человеческий текст → правило повторения. Обратное к `describe`.

    Понимает: каждый день · каждые 3 дня · каждый вторник · по вторникам и
    четвергам · раз в две недели · раз в месяц · раз в квартал · 5 числа ·
    в последний день месяца · последний рабочий день месяца · второй вторник
    месяца · последняя пятница месяца · раз в год в марте · до 31.12.2026 ·
    с переносом на следующий рабочий день · создавать за 3 дня · приостановлено.

    Возвращает правило в том же виде, что принимает `validate_rule`: без ключа
    `anchor` — дату первого цикла текст не задаёт, её выбирают отдельно.

    Пустой словарь на непонятном тексте не отдаём: правило, которое молча
    оказалось «каждый день», хуже отказа. Ошибка идёт с полем, как требует
    контракт, чтобы форма подсветила именно строку ввода.
    """
    if text is None or not str(text).strip():
        raise RuleError([{"field": "text", "error": "Пустая строка"}])

    s = str(text).strip().lower().replace("ё", "е")
    s = re.sub(r"[—–]", " ", s)

    состояние = {}

    # 1. Оговорки. Снимаются первыми: внутри них есть слова «день» и числа,
    # которые в основной части значат совсем другое.
    def _до(m, c):
        д = _дата_из_текста(m.group(1))
        if д is None:
            raise RuleError([{"field": "until",
                              "error": f"Дату окончания не понял: «{m.group(1)}»"}])
        c["until"] = д

    s = _срезать(s, r"\bдо\s+(\d{4}-\d{2}-\d{2}|\d{1,2}[.\-/]\d{1,2}[.\-/]\d{2,4})",
                 _до, состояние)
    s = _срезать(s, r"\bсоздавать\s+за\s+(\d+)\s*д\w*",
                 lambda m, c: c.__setitem__("lead_days", int(m.group(1))), состояние)
    s = _срезать(s, r"\b(приостановлен\w*|пауза|на\s+паузе)\b",
                 lambda m, c: c.__setitem__("paused", True), состояние)

    # «Последний рабочий день месяца» — это не отдельная сущность, а сумма двух
    # полей: последнее число плюс перенос назад (см. `shift_workday`). Ловим
    # фразой целиком, потому что по словам она распалась бы на «последний день»
    # и повисшее «рабочий».
    def _рабочий_день(m, c):
        c["bymonthday"] = [-1 if m.group(1).startswith("последн") else 1]
        c["holiday_shift"] = "before" if m.group(1).startswith("последн") else "after"

    s = _срезать(s, r"\b(последн\w+|перв\w+)\s+рабоч\w+\s+д(?:ень|ня)\s*(?:месяца)?",
                 _рабочий_день, состояние)

    def _перенос(m, c):
        c["holiday_shift"] = "before" if "предыдущ" in m.group(0) else "after"

    s = _срезать(s, r"(?:с\s+выходного\s+)?(?:перенос\w*\s+)?на\s+"
                    r"(?:предыдущ\w+|следующ\w+)\s+рабоч\w+\s+д\w+", _перенос, состояние)

    # Склейка из `_setpos_caption`: «последний из дней недели: пн, пт». Слова
    # «дней» и «недели» в ней служебные, а по словарю они частота — вырезаем.
    s = re.sub(r"\bиз\s+дней\s+недели\b", " ", s)

    # «3-й день с конца месяца» и «3-й с конца вторник» — счёт от конца цифрой.
    отрицательные_дни, отрицательные_позиции = [], []
    while True:
        m = re.search(r"\b(\d+)-?[йея]?\s+день\s+с\s+конца", s)
        if not m:
            break
        отрицательные_дни.append(-int(m.group(1)))
        s = (s[:m.start()] + " " + s[m.end():]).strip()
    while True:
        m = re.search(r"\b(\d+)-?[йея]?\s+с\s+конца", s)
        if not m:
            break
        отрицательные_позиции.append(-int(m.group(1)))
        s = (s[:m.start()] + " " + s[m.end():]).strip()

    # 2. Основная часть — по словам.
    слова = re.findall(r"[а-яa-z0-9]+", s)
    разобрано = [(t, *_вид_слова(t)) for t in слова]
    # Оговорка могла съесть строку целиком («последний рабочий день месяца»), и
    # это законно: она сама задаёт и число месяца, и перенос.
    if not any(вид for _, вид, _ in разобрано) and not состояние.get("bymonthday"):
        raise RuleError([{"field": "text",
                          "error": f"Не понял, как часто повторять: «{text}»"}])

    дни = [з for _, в, з in разобрано if в == "day"]
    месяцы = [з for _, в, з in разобрано if в == "month"]
    порядковые = [з for _, в, з in разобрано if в == "ordinal"]

    # Число месяца от порядкового слова: «последний день месяца» → -1. Отличается
    # от вхождения дня недели («последний вторник») тем, что рядом стоит «день».
    # Само это «день» из разбора выбывает: иначе оно же объявит правило
    # ежедневным, и «в последний день месяца» станет «каждый день».
    числа_месяца = list(отрицательные_дни)
    съедено = set()
    for i, (_, вид, значение) in enumerate(разобрано):
        if вид != "ordinal" or i + 1 >= len(разобрано):
            continue
        следующее, вид_следующего, _ = разобрано[i + 1]
        if вид_следующего == "period" and следующее in ("день", "дня"):
            числа_месяца.append(значение)
            порядковые.remove(значение)
            съедено.add(i + 1)

    # Числа рядом со словом «число» — это дни месяца, рядом со словом периода —
    # шаг. Соседство, а не позиция: «5 числа» и «числа: 5, 15» одинаково верны.
    интервал = None
    for i, (_, вид, значение) in enumerate(разобрано):
        if вид != "number":
            continue
        соседи = [разобрано[j][1] for j in (i - 1, i + 1) if 0 <= j < len(разобрано)]
        соседние_слова = [разобрано[j][0] for j in (i - 1, i + 1)
                          if 0 <= j < len(разобрано)]
        if "monthday-marker" in соседи:
            числа_месяца.append(значение)
        elif "period" in соседи or any(w in НАРЕЧИЯ for w in соседние_слова):
            интервал = значение
        elif not дни and not порядковые and (числа_месяца or "monthday-marker" in
                                             [в for _, в, _ in разобрано]):
            числа_месяца.append(значение)

    # Частота. Наречие несёт её вместе с шагом, слово периода — только частоту.
    частота = None
    for i, (_, вид, значение) in enumerate(разобрано):
        if i in съедено:
            continue
        if вид == "adverb":
            частота, интервал = значение[0], интервал or значение[1]
        elif вид == "period":
            if значение == "quarterly":
                частота, интервал = "monthly", интервал or 3
            else:
                частота = частота or значение

    # Частота без слова периода: её задаёт то, что человек перечислил. День
    # недели без «месяца» — недельное правило; число месяца или вхождение дня
    # недели — месячное.
    if частота is None:
        if порядковые and дни:
            частота = "monthly"
        elif дни:
            частота = "weekly"
        elif числа_месяца or состояние.get("bymonthday"):
            # «Последний рабочий день месяца» снят оговоркой целиком, и в
            # основной части не осталось ни слова — частоту задаёт она сама.
            частота = "monthly"
        elif месяцы:
            частота = "yearly"
    if частота is None:
        raise RuleError([{"field": "text",
                          "error": f"Не понял, как часто повторять: «{text}»"}])

    # «Второй вторник» при недельной частоте смысла не имеет: вхождение в месяце
    # считается по месяцу. Слово «месяц» человек при этом опускает («второй
    # вторник» вместо «второй вторник месяца»), поэтому доворачиваем сами.
    if частота == "weekly" and порядковые:
        частота = "monthly"

    правило = {"freq": частота}
    if интервал and интервал != 1:
        правило["interval"] = интервал
    if дни:
        правило["byweekday"] = sorted(set(дни))
    if числа_месяца and частота in ("monthly", "yearly"):
        правило["bymonthday"] = sorted(set(числа_месяца))
    позиции = отрицательные_позиции + порядковые
    if позиции and частота in ("monthly", "yearly"):
        правило["bysetpos"] = sorted(set(позиции))
    if месяцы and частота in ("monthly", "yearly"):
        правило["bymonth"] = sorted(set(месяцы))
    правило.update(состояние)

    ошибки = validate_rule(правило, start=date(2000, 1, 3))
    if ошибки:
        raise RuleError(ошибки)
    return правило
