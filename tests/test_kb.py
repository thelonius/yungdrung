# --- производительность на целевом объёме ----------------------------------

def test_пятьсот_записей_сканируются_быстро():
    """Целевой объём из задания: 500 записей базы знаний. Замер на рабочей машине:
    1,2 мс на текст через индекс, 2,5 мс без кэша разбора, около 11 мс перебором
    всех названий; разбор одного нового слова стоит около 50 мкс, повторный из
    кэша — доли микросекунды.

    Порог в 50 мс ни перебора, ни потери кэша не ловит: и то и другое в него
    укладывается. Он держит только грубый обвал — квадратичный проход по названиям
    или разбор внутри цикла. Утрату индекса и кэша ловить временем на чужой машине
    бессмысленно, для этого нужен замер против базового уровня, а не константа."""
    записи = [{"id": f"e{i}", "title": f"Организация Номер{i:04d}"} for i in range(500)]
    большой = kb.build_index(записи)
    текст = ("Согласовать смету с Организацией Номер0123 и уточнить сроки поставки "
             "у подрядчика, затем отправить письмо в бухгалтерию ") * 5
    начало = time.perf_counter()
    for _ in range(20):
        найдено = kb.find_mentions(текст, большой)
    прошло = (time.perf_counter() - начало) / 20
    assert [м["entry_id"] for м in найдено] == ["e123"] * 5
    assert прошло < 0.05


