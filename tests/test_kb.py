# --- гипотеза, а не ссылка -------------------------------------------------

def test_распознавание_не_создаёт_ссылку(index):
    """Раздел 7.1: в базу не пишется ничего, пока человек не ответил «да».
    Модуль возвращает гипотезы и не имеет способа записать ссылку сам."""
    м = kb.find_mentions("отдать Говнову денег", index)[0]
    assert м["confirmed"] is False
    assert "confirmed_at" not in м
    # Повторное сканирование того же текста снова даёт гипотезу, а не факт.
    ещё_раз = kb.find_mentions("отдать Говнову денег", index)[0]
    assert ещё_раз["confirmed"] is False


def test_ссылка_появляется_только_после_подтверждения(index):
    м = kb.find_mentions("отдать Говнову денег", index)[0]
    ссылка = kb.confirm(м, at=datetime(2026, 8, 17, 10, 0))
    assert ссылка["confirmed"] is True
    assert ссылка["confirmed_at"] == "2026-08-17T10:00:00"
    assert ссылка["entry_id"] == "govnov"
    assert (ссылка["offset_start"], ссылка["offset_end"]) == (7, 14)


def test_подтверждение_не_трогает_исходную_гипотезу(index):
    """Интерфейс показывает тот же список дальше: подтверждение одного упоминания
    не должно незаметно менять соседние."""
    найдено = kb.find_mentions("Василию Говнову и Петру Семёнову", index)
    kb.confirm(найдено[0], at=datetime(2026, 8, 17, 10, 0))
    assert найдено[0]["confirmed"] is False
    assert найдено[1]["confirmed"] is False


def test_повторное_подтверждение_идемпотентно(index):
    """КОНТРАКТ: оболочка вправе повторить запрос после обрыва, второй ссылки
    от этого появиться не должно."""
    м = kb.find_mentions("отдать Говнову денег", index)[0]
    первое = kb.confirm(м, at=datetime(2026, 8, 17, 10, 0))
    второе = kb.confirm(первое, at=datetime(2026, 8, 18, 12, 0))
    assert второе == первое


