def test_отклонённое_совпадение_больше_не_предлагается(index):
    текст = "отдать Говнову денег"
    м = kb.find_mentions(текст, index)[0]
    исключения = kb.reject(м)
    assert kb.find_mentions(текст, index, excluded=исключения) == []


def test_отклонение_привязано_к_написанию_а_не_к_месту(index):
    """Ключ исключения не содержит смещений: правка соседнего слова сдвигает
    текст, а ответ «нет» должен пережить правку."""
    м = kb.find_mentions("отдать Говнову денег", index)[0]
    исключения = kb.reject(м)
    сдвинутый = "срочно отдать Говнову денег"
    assert kb.find_mentions(сдвинутый, index, excluded=исключения) == []


def test_отклонение_одной_формы_не_гасит_другую_запись(index):
    м = kb.find_mentions("отдать Говнову денег", index)[0]
    исключения = kb.reject(м)
    найдено = kb.find_mentions("написать Петру Семёнову", index, excluded=исключения)
    assert [м["entry_id"] for м in найдено] == ["semenov"]


