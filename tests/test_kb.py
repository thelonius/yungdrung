# --- неоднозначность -------------------------------------------------------

def test_одинаковая_фамилия_у_двух_записей_не_опознаётся_одним_словом():
    """Есть «Василий Говнов» и «Мария Говнова»: спрашивать «Это Василий Говнов?»
    по слову «Говнову» нечестно, ответа не знает и человек."""
    двое = kb.build_index([
        {"id": "vg", "title": "Василий Говнов"},
        {"id": "mg", "title": "Мария Говнова"},
    ])
    assert kb.find_mentions("отдать Говнову денег", двое) == []
    найдено = kb.find_mentions("отдать Василию Говнову денег", двое)
    assert [м["entry_id"] for м in найдено] == ["vg"]


def test_однофамильцы_не_подменяют_друг_друга():
    """«Говнова» — родительный от «Говнов» и именительный от «Говнова» сразу. Запись
    предлагается по той основе, которая привела к ней одна: «говнова» принадлежит
    только Марии, «говнов» — обеим. Пока однозначность считалась по слову целиком, по
    этой фамилии всплывал и Василий, а кто из двоих победит, решал алфавит id."""
    двое = kb.build_index([
        {"id": "a-vasiliy", "title": "Василий Говнов"},
        {"id": "z-mariya", "title": "Мария Говнова"},
    ])
    найдено = kb.find_mentions("отдать Говнова денег", двое)
    assert [м["entry_id"] for м in найдено] == ["z-mariya"]
    assert найдено[0]["matched"] == "Говнова"


def test_однословная_запись_не_подменяется_соседкой_по_основе():
    """«Иванова» — целое название одной записи и падеж другой. Раньше побеждал
    «Иванов»: однозначной признавалась основа «иванова», а совпадение шло по «иванов»."""
    двое = kb.build_index([{"id": "ivanov", "title": "Иванов"},
                           {"id": "ivanova", "title": "Иванова"}])
    найдено = kb.find_mentions("Иванова позвонила", двое)
    assert [м["entry_id"] for м in найдено] == ["ivanova"]


