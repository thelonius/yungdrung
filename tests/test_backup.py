def test_оборвавшееся_восстановление_называет_страховочную_копию(vault, копии,
                                                                monkeypatch):
    """Худший случай: половина файлов новая, половина старая. Ошибка обязана
    сказать, откуда взять целое состояние, иначе человек остаётся с вольтом,
    которому нельзя верить, и без единой подсказки."""
    копия = backup.create(vault, копии, now=datetime(2026, 8, 18, 9, 0))
    задача = vault / "Задачи" / "Заявка на грант ФПГ.md"
    задача.write_text("сегодняшняя работа", encoding="utf-8")

    настоящая = backup.replace_file
    счёт = {"n": 0}

    def сорвётся_на_третьем(tmp, target):
        # 1 — архив страховочной копии, 2 — первый файл вольта, 3 — обрыв.
        счёт["n"] += 1
        if счёт["n"] == 3:
            raise PermissionError("файл держит антивирус")
        настоящая(tmp, target)

    monkeypatch.setattr(backup, "replace_file", сорвётся_на_третьем)

    with pytest.raises(backup.BackupError) as e:
        backup.restore(копия["file"], vault, safety_dir=копии,
                       now=datetime(2026, 8, 18, 12, 0))

    assert e.value.field == "restore"
    assert "База/6805.md" in e.value.message
    assert e.value.as_json()["restored"] == 1
    подстраховка = e.value.as_json()["safety_copy"]
    with zipfile.ZipFile(подстраховка) as z:
        assert z.read("Задачи/Заявка на грант ФПГ.md").decode("utf-8") == \
            "сегодняшняя работа"
    # До сорвавшегося файла очередь не дошла — работа этого дня ещё в вольте.
    assert задача.read_text(encoding="utf-8") == "сегодняшняя работа"


