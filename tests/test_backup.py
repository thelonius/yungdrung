def имена_в_архиве(path):
    with zipfile.ZipFile(path) as z:
        return sorted(n for n in z.namelist() if n != backup.MANIFEST)


def положить_копию(папка, имя):
    """Файл-пустышка вместо настоящей копии: ротация смотрит только на имя."""
    (папка / имя).write_bytes(b"zip")


def сделать_базу(путь, названия, wal=False):
    """База из одной таблицы задач — столько же данных, сколько во frontmatter.

    Соединение возвращается открытым: закрытие последнего соединения сбрасывает
    WAL в основной файл, а тестам про WAL нужно ровно обратное.
    """
    conn = sqlite3.connect(str(путь))
    if wal:
        conn.execute("pragma journal_mode=wal")
    conn.execute("create table задачи (id integer primary key, title text)")
    conn.executemany("insert into задачи values (?, ?)",
                     list(enumerate(названия, 1)))
    conn.commit()
    return conn


def задачи(база):
    conn = sqlite3.connect(str(база))
    try:
        return [r[0] for r in conn.execute("select title from задачи order by id")]
    finally:
        conn.close()


def задачи_из_копии(архив, имя, куда):
    """Достать базу из архива и прочитать. Копия обязана открываться сама по
    себе: без спутников, без нашего кода и без починки."""
    куда.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(архив) as z:
        z.extract(имя, куда)
    return задачи(куда / имя)


