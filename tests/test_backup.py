def test_битый_снимок_копию_не_создаёт(tmp_path, копии, monkeypatch):
    """Копия, про которую известно, что она не читается, хуже отсутствия копии:
    заказчик считает данные защищёнными. Останавливаемся, пока оригинал цел, и
    прежние копии в папке при этом не трогаем."""
    положить_копию(копии, "вольт-2026-08-17-090000.zip")
    база = tmp_path / "вольт.db"
    сделать_базу(база, ["Заявка"]).close()
    monkeypatch.setattr(backup, "check_sqlite", lambda путь: "page 3 is never used")

    with pytest.raises(backup.BackupError) as e:
        backup.create(база, копии, now=datetime(2026, 8, 18, 9, 0))

    assert e.value.field == "vault"
    assert "page 3 is never used" in e.value.message
    assert [p.name for p in копии.iterdir()] == ["вольт-2026-08-17-090000.zip"]


