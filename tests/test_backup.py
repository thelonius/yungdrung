def собрать_вольт_по_выгрузке(данные, куда):
    """Собрать вольт заново, пользуясь только полями выгрузки.

    Так проверяется R11: ровно это сделает чужая программа, у которой нашего
    кода нет. Ни `engine`, ни `backup` здесь не участвуют — только `json`,
    `yaml` и то, что написано в файле экспорта.
    """
    записи = ([(з, "task") for з in данные["tasks"]] +
              [(з, "note") for з in данные["notes"]])
    for запись, тип in записи:
        путь = куда / запись["file"]
        путь.parent.mkdir(parents=True, exist_ok=True)
        # "schema" — понятие только задачи (TASK_KNOWN_KEYS в storage.py); у
        # заметки его в схеме нет вовсе, и экспорт его для заметок никогда не
        # отдавал (ни в старой реализации export(), ни в новой). Дописать его
        # сюда безусловно для обоих типов значило бы засорить extra заметки
        # значением, которого сама заметка никогда не несла.
        шапка = {"type": тип, "title": запись["title"]}
        if тип == "task":
            шапка["schema"] = данные["schema"]
            шапка["created"] = запись["created"]
        if запись["tags"]:
            шапка["tags"] = запись["tags"]
        шапка.update(запись["extra"])
        if тип == "task":
            шапка["steps"] = запись["steps"]
        путь.write_text(
            "---\n"
            + yaml.safe_dump(шапка, allow_unicode=True, sort_keys=False)
            + "---\n\n" + запись["body"] + "\n",
            encoding="utf-8")


