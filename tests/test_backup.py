# --- копия базы SQLite -----------------------------------------------------

def test_вид_хранилища_читается_с_диска(tmp_path, vault):
    """Решение принимается по заголовку файла, а не по расширению и не по
    настройке: `.db`, набитый текстом, базой не является, а базой без
    расширения — является."""
    настоящая = tmp_path / "вольт.дан"
    сделать_базу(настоящая, ["Заявка"]).close()
    подделка = tmp_path / "вольт.db"
    подделка.write_text("это просто текст", encoding="utf-8")

    assert backup.storage_kind(настоящая) == "sqlite"
    assert backup.storage_kind(подделка) == "file"
    assert backup.storage_kind(vault) == "folder"
    assert backup.storage_kind(tmp_path / "нет такого") == "missing"


def test_снимок_снятый_посреди_транзакции_читается(tmp_path, копии):
    """Побайтовая копия живого файла базы попадает в середину чужой транзакции.
    Штатный снимок отдаёт зафиксированное состояние: две задачи, которые успели
    закоммититься, и ни одной из открытой транзакции."""
    база = tmp_path / "вольт.db"
    conn = сделать_базу(база, ["Заявка на грант ФПГ", "Договор с Говновым"])
    пишущее = sqlite3.connect(str(база))
    пишущее.execute("insert into задачи values (3, 'ещё не закоммичена')")
    try:
        итог = backup.create(база, копии, now=datetime(2026, 8, 18, 9, 0))
        снимок = tmp_path / "из копии" / "вольт.db"
        assert задачи_из_копии(итог["file"], "вольт.db", tmp_path / "из копии") == \
            ["Заявка на грант ФПГ", "Договор с Говновым"]
        assert backup.check_sqlite(снимок) == "ok"
    finally:
        пишущее.rollback()
        пишущее.close()
        conn.close()


def test_снимок_берёт_то_чего_в_файле_базы_ещё_нет(tmp_path, копии):
    """Режим WAL: свежие страницы лежат в журнале, а в самом файле базы их нет
    до контрольной точки. Побайтовая копия файла в этот момент не содержит даже
    таблицы — снимок содержит все три задачи."""
    база = tmp_path / "вольт.db"
    conn = сделать_базу(база, ["Заявка", "Договор", "Отчёт"], wal=True)
    try:
        побайтово = tmp_path / "побайтово.db"
        побайтово.write_bytes(база.read_bytes())
        with pytest.raises(sqlite3.DatabaseError):
            задачи(побайтово)

        итог = backup.create(база, копии, now=datetime(2026, 8, 18, 9, 0))
        assert задачи_из_копии(итог["file"], "вольт.db", tmp_path / "из копии") == \
            ["Заявка", "Договор", "Отчёт"]
    finally:
        conn.close()


