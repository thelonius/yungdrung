    архив = копии / "вольт-2026-08-18-090000.zip"
    with zipfile.ZipFile(архив, "w") as z:
        z.writestr(backup.MANIFEST, "{манифест не дописался")
        z.writestr("Задачи/Заявка на грант ФПГ.md", ЗАДАЧА)

    описание = backup.describe(архив)
    assert описание["files"] == 1
    assert описание["storage"] is None and описание["ours"] is False

    (vault / "Задачи" / "Заявка на грант ФПГ.md").write_text("испорчено", encoding="utf-8")
    итог = backup.restore(архив, vault, safety_dir=копии,
                          now=datetime(2026, 8, 18, 12, 0))
    assert итог["restored"] == 1
    assert (vault / "Задачи" / "Заявка на грант ФПГ.md").read_text(encoding="utf-8") == ЗАДАЧА


