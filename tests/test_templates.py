def test_предпросмотр_показывает_даты_и_дни_недели():
    строки = templates.preview(шаблон(), date(2026, 8, 17))
    assert [(с["control_date"], с["weekday"]) for с in строки] == [
        ("2026-08-17 10:00", "пн"), ("2026-08-20 14:00", "чт"), ("2026-08-27", "чт")]


def test_предпросмотр_отмечает_попадание_на_выходной():
    """Старт в пятницу 21 августа, сдвиг на день — суббота 22-го."""
    один = шаблон(steps=[{"title": "Оплатить", "offset_days": 1, "time_of_day": "09:00"}])
    строка = templates.preview(один, date(2026, 8, 21))[0]
    assert строка["control_date"] == "2026-08-22 09:00"
    assert строка["on_weekend"] is True


def test_предпросмотр_с_рабочим_временем_показывает_когда_всплывёт():
    """Контроль в субботу 09:00, выходные выключены — уведомление в понедельник
    24-го в 09:00. Сама дата контроля при этом не сдвигается."""
    один = шаблон(steps=[{"title": "Оплатить", "offset_days": 1, "time_of_day": "09:00"}])
    строка = templates.preview(один, date(2026, 8, 21), work=worktime.settings())[0]
    assert строка["control_date"] == "2026-08-22 09:00"
    assert строка["show_at"] == "2026-08-24T09:00"


def test_предпросмотр_нумерует_шаги_с_единицы():
    assert [с["position"] for с in templates.preview(шаблон(), date(2026, 8, 17))] == [1, 2, 3]


def test_при_включённых_выходных_суббота_не_помечается_выходным():
    """Работа по выходным включена, контроль в субботу 22 августа: показ в ту же
    субботу. Пометка выходного при этом означала бы, что одна строка
    предпросмотра противоречит сама себе."""
    один = шаблон(steps=[{"title": "Оплатить", "offset_days": 1, "time_of_day": "09:00"}])
    строка = templates.preview(один, date(2026, 8, 21),
                               work=worktime.settings(weekends=True))[0]
    assert строка["control_date"] == "2026-08-22 09:00"
    assert строка["on_weekend"] is False
    assert строка["show_at"] == "2026-08-22T09:00"


def test_предпросмотр_берёт_начало_рабочего_дня_из_настроек():
    """Рабочий день с 11:00: контроль в 09:00 понедельника всплывёт в 11:00.
    Своих значений рабочего времени у предпросмотра нет, они приходят
    параметром — заказчик их меняет."""
    один = шаблон(steps=[{"title": "Оплатить", "offset_days": 0, "time_of_day": "09:00"}])
    строка = templates.preview(один, date(2026, 8, 17),
                               work=worktime.settings(start=time(11, 0)))[0]
    assert строка["show_at"] == "2026-08-17T11:00"


def test_дата_в_поле_сдвига_не_роняет_предпросмотр():
    """20260818 в поле сдвига уводит дату за пределы календаря. Форма считает
    предпросмотр до сохранения, то есть до проверки, — и должна получить ошибку
    значения, а не OverflowError из середины расчёта."""
    плохой = шаблон(steps=[{"title": "Шаг", "offset_days": 20260818}])
    assert [e["field"] for e in templates.validate_template(плохой)] == [
        "steps.0.offset_days"]
    with pytest.raises(ValueError):
        templates.preview(плохой, date(2026, 8, 17))


def test_предпросмотр_от_тридцать_первого_января_держит_календарь_и_выходные():
    """Старт в субботу 31 января 2026. В феврале 28 дней, поэтому +28 — это
    суббота 28 февраля, +29 — воскресенье 1 марта, +31 — вторник 3 марта.
    Первые три шага попали на выходные: показ уезжает на понедельник 2 февраля
    и на понедельник 2 марта, а даты контроля остаются субботними."""
    длинный = шаблон(steps=[
        {"title": "старт", "offset_days": 0, "time_of_day": "10:00"},
        {"title": "конец февраля", "offset_days": 28, "time_of_day": "14:00"},
        {"title": "начало марта", "offset_days": 29},
        {"title": "через месяц", "offset_days": 31},
    ])
    строки = templates.preview(длинный, date(2026, 1, 31), work=worktime.settings())
    assert [(с["control_date"], с["weekday"], с["on_weekend"], с["show_at"])
            for с in строки] == [
        ("2026-01-31 10:00", "сб", True, "2026-02-02T09:00"),
        ("2026-02-28 14:00", "сб", True, "2026-03-02T09:00"),
        ("2026-03-01", "вс", True, "2026-03-02T09:00"),
        ("2026-03-03", "вт", False, "2026-03-03T09:00"),
    ]


def test_те_же_даты_при_работе_по_выходным_показываются_в_свой_день():
    """Тот же шаблон и тот же старт, но заказчик работает по выходным. Даты
    контроля не меняются, показ никуда не уезжает, и субботы перестают быть
    выходными. Шаг без времени всё равно ждёт начала рабочего дня: дата без часа
    означает весь день, а он начинается в 09:00."""
    длинный = шаблон(steps=[
        {"title": "старт", "offset_days": 0, "time_of_day": "10:00"},
        {"title": "конец февраля", "offset_days": 28, "time_of_day": "14:00"},
        {"title": "начало марта", "offset_days": 29},
    ])
    строки = templates.preview(длинный, date(2026, 1, 31),
                               work=worktime.settings(weekends=True))
    assert [(с["control_date"], с["on_weekend"], с["show_at"]) for с in строки] == [
        ("2026-01-31 10:00", False, "2026-01-31T10:00"),
        ("2026-02-28 14:00", False, "2026-02-28T14:00"),
        ("2026-03-01", False, "2026-03-01T09:00"),
    ]


@pytest.mark.parametrize("выходные", [False, True])
def test_пометка_выходного_и_момент_показа_не_спорят(выходные):
    """Строка предпросмотра не может одновременно метить день выходным и
    назначать показ на него же. Обе пометки считает один `worktime.is_workday`,
    поэтому от настройки они меняются вместе. Неделя от понедельника 17 августа
    с контролем в 10:00 — все восемь дней внутри рабочих часов, так что дату
    показа двигают только выходные."""
    неделя = шаблон(steps=[{"title": f"день {i}", "offset_days": i,
                            "time_of_day": "10:00"} for i in range(8)])
    работа = worktime.settings(weekends=выходные)
    строки = templates.preview(неделя, date(2026, 8, 17), work=работа)
    assert len(строки) == 8
    for строка in строки:
        показ_в_свой_день = строка["show_at"][:10] == строка["control_date"][:10]
        assert строка["on_weekend"] == (not показ_в_свой_день), строка


