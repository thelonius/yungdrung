class СписокВПамяти(templates.Store):
    """Наследник склада, написанный по минимуму: столько же кода потребует
    SQLite. Списки копируются, чтобы вызывающий не правил хранилище мимо save."""

    def __init__(self):
        self.строки = []

    def _load(self):
        return [dict(t) for t in self.строки]

    def _commit(self, шаблоны):
        self.строки = [dict(t) for t in шаблоны]


def test_наследнику_склада_хватает_чтения_и_записи():
    """Проверка, приведение к каноническому виду, поиск по имени без учёта
    регистра и идемпотентность достались от базового класса. Наследник добавил
    только `_load` и `_commit`, а расчёты о нём ничего не знают."""
    склад = СписокВПамяти()
    склад.save(шаблон())
    склад.save(шаблон())
    assert [t["name"] for t in склад.all()] == ["Квартальный отчёт"]
    assert склад.get("квартальный ОТЧЁТ")["steps"][1]["offset_days"] == 3
    with pytest.raises(templates.TemplateError):
        склад.save(шаблон(name=""))
    assert склад.delete("Квартальный отчёт") is True
    assert склад.delete("Квартальный отчёт") is False


def test_расчёт_обходится_без_склада():
    """Обратная сторона границы: `expand` и `preview` принимают шаблон обычным
    словарём. Откуда он взялся — из файла, из формы или из будущей таблицы —
    расчёту безразлично, и сохранять его ради предпросмотра не нужно."""
