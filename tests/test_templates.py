# --- несуществующие даты ---------------------------------------------------

def test_сдвиг_с_тридцать_первого_числа_не_даёт_несуществующей_даты():
    """Старт 31 января 2026. В феврале 28 дней, поэтому:
       +28 → 28 февраля, +29 → 1 марта, +31 → 3 марта.
    Сдвиг календарный, а не «то же число в другом месяце», — «31 февраля»
    получиться неоткуда."""
    длинный = шаблон(steps=[
        {"title": "старт", "offset_days": 0},
        {"title": "конец февраля", "offset_days": 28},
        {"title": "начало марта", "offset_days": 29},
        {"title": "через месяц", "offset_days": 31},
    ])
    assert даты(templates.expand(длинный, date(2026, 1, 31))) == [
        "2026-01-31", "2026-02-28", "2026-03-01", "2026-03-03"]


def test_тот_же_сдвиг_в_високосном_году_попадает_на_другое_число():
    """Тот же шаблон, старт 31 января 2028. В феврале 29 дней, значит +29 — это
    29 февраля, а +30 — 1 марта. Год расчёт меняет, но несуществующей даты не
    появляется и здесь."""
    длинный = шаблон(steps=[
        {"title": "старт", "offset_days": 0},
        {"title": "конец февраля", "offset_days": 29},
        {"title": "начало марта", "offset_days": 30},
    ])
    assert даты(templates.expand(длинный, date(2028, 1, 31))) == [
        "2028-01-31", "2028-02-29", "2028-03-01"]


def test_шаблон_из_задачи_с_тридцать_первого_числа_повторяется_на_другом_месяце():
    """Задача шла с 31 января по 3 марта: расстояние 31 день (28 дней февраля
    плюс три мартовских). «Повторить» с 31 марта даёт 31 марта и 1 мая, потому
    что в апреле 30 дней. Ни «31 февраля», ни «31 апреля» в цепочке
    задача → шаблон → задача не появляется."""
    meta = {"title": "Отчёт за январь", "tags": [], "steps": [
        {"title": "Собрать выписки", "control_date": datetime(2026, 1, 31, 10, 0)},
        {"title": "Отправить в фонд", "control_date": date(2026, 3, 3)},
    ]}
    шаб = templates.template_from_task(meta, name="Отчёт за март")
    assert [ш["offset_days"] for ш in шаб["steps"]] == [0, 31]
    assert даты(templates.expand(шаб, date(2026, 3, 31))) == [
        "2026-03-31 10:00", "2026-05-01"]


