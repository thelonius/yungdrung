#!/usr/bin/env python3
"""Тесты `domain.ru_dates.extract_when` — даты внутри свободной фразы.

Сам `parse_date_input` покрыт в test_engine.py (через реэкспорт `engine.*`) и
здесь не дублируется: `extract_when` только выбирает, какой хвост фразы ему
отдать, и тесты ниже проверяют ровно этот выбор — границы, название, отказ.
"""
import sys
from datetime import date, datetime
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from domain.ru_dates import extract_when, parse_date_input  # noqa: E402

TODAY = date(2026, 9, 8)
NOW = datetime(2026, 9, 8, 11, 0)


@pytest.mark.parametrize("фраза, название, момент, кусок", [
    ("позвонить Василию завтра в полдесятого", "позвонить Василию",
     datetime(2026, 9, 9, 9, 30), "завтра в полдесятого"),
    ("оплатить налоги +3", "оплатить налоги", date(2026, 9, 11), "+3"),
    ("сдать отчёт 15 марта в 10", "сдать отчёт", datetime(2027, 3, 15, 10, 0), "15 марта в 10"),
    ("созвон в 15:00", "созвон", datetime(2026, 9, 8, 15, 0), "в 15:00"),
    ("продлить страховку пн", "продлить страховку", date(2026, 9, 14), "пн"),
    ("выписка через 3 дня", "выписка", date(2026, 9, 11), "через 3 дня"),
    ("завтра", "", date(2026, 9, 9), "завтра"),
])
def test_дата_отделяется_от_названия(фраза, название, момент, кусок):
    имя, когда, границы = extract_when(фраза, TODAY)
    assert (имя, когда) == (название, момент)
    assert фраза[границы[0]:границы[1]] == кусок
    # Распознанный кусок разбирается сам по себе в тот же момент: подсветка
    # в форме показывает ровно то, что ядро потом примет как дату.
    assert parse_date_input(кусок, TODAY) == когда


@pytest.mark.parametrize("фраза", [
    "позвонить Василию", "отчёт за март", "купить пять мешков", "встреча в пятницу",
])
def test_без_даты_фраза_возвращается_целиком(фраза):
    assert extract_when(фраза, TODAY) == (фраза, None, None)


def test_пусто_и_none():
    assert extract_when("", TODAY) == ("", None, None)
    assert extract_when("   ", TODAY) == ("", None, None)
    assert extract_when(None, TODAY) == ("", None, None)


def test_через_час_требует_now_как_и_сам_разбор():
    assert extract_when("перезвонить через час", TODAY) == ("перезвонить через час", None, None)
    имя, когда, _ = extract_when("перезвонить через час", TODAY, now=NOW)
    assert (имя, когда) == ("перезвонить", datetime(2026, 9, 8, 12, 0))


def test_голое_число_в_конце_становится_временем_как_в_поле_даты():
    """Осознанная граница: «заказать 10» — это 10:00 сегодня, ровно как «в 10»
    в поле даты. Форма это показывает, человек правит; угадывать за него не
    надо. Тест пиннит поведение, чтобы оно не поменялось молча."""
    имя, когда, _ = extract_when("заказать 10", TODAY)
    assert (имя, когда) == ("заказать", datetime(2026, 9, 8, 10, 0))


@pytest.mark.parametrize("название", ["позвонить Василию", "оплатить",
                                      "свести смету по фундаменту"])
@pytest.mark.parametrize("дата", ["завтра", "+7", "18.10", "пн в 9", "послезавтра в полдень",
                                  "15 марта 2027", "через 2 дня 18:00", "без четверти десять"])
def test_склейка_названия_и_даты_разбирается_обратно(название, дата):
    фраза = f"{название} {дата}"
    имя, когда, границы = extract_when(фраза, TODAY)
    assert имя == название
    assert когда == parse_date_input(дата, TODAY)
    assert фраза[границы[0]:] == дата
