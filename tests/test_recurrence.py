    правило = {"freq": "weekly", "byweekday": [1]}
    assert recurrence.next_dates(правило, ПН17, 5) == [
        date(2026, 8, 18), date(2026, 8, 25), date(2026, 9, 1),
        date(2026, 9, 8), date(2026, 9, 15)]


