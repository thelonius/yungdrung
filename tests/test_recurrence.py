@pytest.mark.parametrize("день, режим, ожидаем", [
    (date(2026, 8, 22), "after", date(2026, 8, 24)),   # суббота → понедельник
    (date(2026, 8, 23), "after", date(2026, 8, 24)),   # воскресенье → понедельник
    (date(2026, 8, 22), "before", date(2026, 8, 21)),  # суббота → пятница
    (date(2026, 8, 23), "before", date(2026, 8, 21)),  # воскресенье → пятница
    (date(2026, 8, 20), "after", date(2026, 8, 20)),   # четверг не двигается
    (date(2026, 8, 20), "before", date(2026, 8, 20)),
    (date(2026, 8, 22), "none", date(2026, 8, 22)),    # без переноса
])
def test_перенос_с_выходного(день, режим, ожидаем):
    assert recurrence.shift_workday(день, режим) == ожидаем


def test_при_включённых_выходных_переноса_нет():
    """Если человек работает по выходным, двигать субботу некуда."""
    work = worktime.settings(weekends=True)
    assert recurrence.shift_workday(date(2026, 8, 22), "before", work) == date(2026, 8, 22)


def test_последний_рабочий_день_месяца():
    """Складывается из двух полей: последний день месяца плюс перенос назад.
    31.01 сб → 30.01 · 28.02 сб → 27.02 · 31.03 вт → 31.03 · 30.04 чт → 30.04 ·
    31.05 вс → 29.05 · 30.06 вт → 30.06 · 31.07 пт → 31.07 · 31.08 пн → 31.08."""
    правило = {"freq": "monthly", "bymonthday": -1, "holiday_shift": "before"}
    assert recurrence.next_dates(правило, date(2026, 1, 1), 8) == [
        date(2026, 1, 30), date(2026, 2, 27), date(2026, 3, 31), date(2026, 4, 30),
        date(2026, 5, 29), date(2026, 6, 30), date(2026, 7, 31), date(2026, 8, 31)]


def test_перенос_склеивает_субботу_и_воскресенье_в_один_день():
    """22 и 23 августа — суббота и воскресенье, обе едут на понедельник 24-е.
    Два экземпляра на один день означали бы два одинаковых вопроса за вечер."""
    правило = {"freq": "monthly", "bymonthday": [22, 23], "holiday_shift": "after"}
    assert recurrence.next_dates(правило, date(2026, 8, 1), 3) == [
        date(2026, 8, 24), date(2026, 9, 22), date(2026, 9, 23)]


def test_перенос_назад_может_увести_дату_из_отбора():
    """23 августа — воскресенье, с переносом назад это пятница 21-е. Отбор идёт
    с 22-го, значит цикл уже состоялся и в ближайшие не попадает."""
    правило = {"freq": "monthly", "bymonthday": 23, "holiday_shift": "before"}
    assert recurrence.next_dates(правило, date(2026, 8, 1), 2,
                                 since=date(2026, 8, 22)) == [
        date(2026, 9, 23), date(2026, 10, 23)]


