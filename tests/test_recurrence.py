# --- разбор доходит до сегодняшнего дня -------------------------------------

def test_разбор_доходит_до_свежих_циклов():
    """Недельное правило со стартом в понедельник 05.01.2026 при сегодня 18.08
    накопило 32 незакрытых цикла: понедельники с 12.01 по 17.08. Лимит в дюжину
    раньше резал хвост, и разбор навсегда застревал на марте — пропуск не закрывает
    предыдущий цикл, поэтому назавтра возвращалась та же дюжина."""
    аргументы = dict(previous={"date": date(2026, 1, 5), "closed": False})
    решения = recurrence.due_cycles({"freq": "weekly"}, date(2026, 1, 5),
                                    date(2026, 8, 18), **аргументы)
    assert len(решения) == 12
    assert {р["action"] for р in решения} == {"skip"}
    assert решения[0]["date"] == date(2026, 6, 1)
    assert решения[-1]["date"] == date(2026, 8, 17)

    целиком = recurrence.due_cycles({"freq": "weekly"}, date(2026, 1, 5),
                                    date(2026, 8, 18), limit=40, **аргументы)
    assert len(целиком) == 32
    assert целиком[0]["date"] == date(2026, 1, 12)
    assert целиком[-1]["date"] == date(2026, 8, 17)


