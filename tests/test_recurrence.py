def test_пропущенные_циклы_не_сдвигают_сетку():
    """Ключевое место R23: сетка привязана к календарю, а не к тому, когда о ней
    вспомнили. Правило «5-го числа» стартовало 5 сентября, отбор идёт с 20 ноября —
    следующие даты всё равно пятые числа, а не 20 декабря и 20 января."""
    правило = {"freq": "monthly"}
    assert recurrence.next_dates(правило, date(2026, 9, 5), 3,
                                 since=date(2026, 11, 20)) == [
        date(2026, 12, 5), date(2027, 1, 5), date(2027, 2, 5)]


