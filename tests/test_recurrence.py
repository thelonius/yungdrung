    правило = {"freq": "monthly", "bymonthday": -1, "holiday_shift": "before"}
    строка = recurrence.preview(правило, date(2026, 1, 1), 1)[0]
    assert строка["date"] == date(2026, 1, 30)
    assert строка["shifted_from"] == date(2026, 1, 31)
    assert строка["text"] == "30.01 (пт), перенос с 31.01"


