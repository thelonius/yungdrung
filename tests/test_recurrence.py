ПН17 = date(2026, 8, 17)


def поля(errors):
    return {e["field"] for e in errors}


# --- простые правила: день и неделя ----------------------------------------

def test_каждый_день():
    правило = {"freq": "daily"}
    assert recurrence.next_dates(правило, ПН17, 5) == [
        date(2026, 8, 17), date(2026, 8, 18), date(2026, 8, 19),
        date(2026, 8, 20), date(2026, 8, 21)]


