#!/usr/bin/env python3
"""Подпись к разобранной дате — то, что человек читает под полем формы.

Сам разбор проверяется в test_ru_dates.py; здесь — только оформление ответа
и день недели в нём. День назван всегда: вопрос «какой это день» возникает на
каждом контроле, и по одному числу на него не ответить.
"""
import sys
from datetime import date, datetime
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from core.dates import parse_when  # noqa: E402

СЕГОДНЯ = date(2026, 9, 17)      # четверг
СЕЙЧАС = datetime(2026, 9, 17, 10, 0)


@pytest.mark.parametrize("ввод,подпись", [
    ("сегодня", "сегодня, четверг"),
    ("завтра", "завтра, пятница"),
    ("послезавтра", "послезавтра, суббота"),
    ("+3", "20.09.2026, воскресенье, через 3 дн."),
    ("пн", "21.09.2026, понедельник, через 4 дн."),
    ("завтра в 9:30", "завтра, пятница, в 09:30"),
    ("+10 18:00", "27.09.2026, воскресенье, в 18:00, через 10 дн."),
])
def test_подпись(ввод, подпись):
    r = parse_when(ввод, СЕГОДНЯ, now=СЕЙЧАС)
    assert r.ok and r.label == подпись


def test_прошлое_помечено_и_тоже_названо():
    r = parse_when("15.09.2026", СЕГОДНЯ, now=СЕЙЧАС)
    assert r.label == "15.09.2026, вторник, 2 дн. назад"
    assert r.past is True


def test_день_недели_совпадает_с_календарём():
    # Заодно ловит сдвиг таблицы имён на единицу: у date.weekday()
    # понедельник нулевой.
    r = parse_when("2026-09-19", СЕГОДНЯ, now=СЕЙЧАС)
    assert "суббота" in r.label
    assert date(2026, 9, 19).weekday() == 5


def test_непонятный_ввод_остаётся_ответом_а_не_ошибкой():
    r = parse_when("послепослезавтра", СЕГОДНЯ, now=СЕЙЧАС)
    assert r.ok is False and r.label is None and r.error
